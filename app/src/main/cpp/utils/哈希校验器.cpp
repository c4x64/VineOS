  for(int 轮=0;轮<64;++轮){ uint32_t 大西格玛1=右旋(戊,6)^右旋(戊,11)^右旋(戊,25); uint32_t 选择=(戊&己)^(~戊&庚); uint32_t 临1=辛+大西格玛1+选择+常量表_K[轮]+消息[轮]; uint32_t 大西格玛0=右旋(甲,2)^右旋(甲,13)^右旋(甲,22); uint32_t 多数=(甲&乙)^(甲&丙)^(乙&丙); uint32_t 临2=大西格玛0+多数; 辛=庚; 庚=己; 己=戊; 戊=丁+临1; 丁=丙; 丙=乙; 乙=甲; 甲=临1+临2; }
