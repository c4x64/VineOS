// 更新：缓冲未满先填缓冲，凑满 64 字节即压缩；大段直接逐块压缩。
void 沙256上下文::更新(const uint8_t* 数据, size_t 长度) {
  if(!数据||长度==0) return; 位计数+= (uint64_t)长度*8; size_t 偏移=0;
  if(缓冲长度>0){ size_t 需=64-缓冲长度; size_t 取=长度<需?长度:需; memcpy(缓冲+缓冲长度,数据,取); 缓冲长度+=取; 偏移+=取; if(缓冲长度==64){ 压缩块(缓冲); 缓冲长度=0; } }
  while(偏移+64<=长度){ 压缩块(数据+偏移); 偏移+=64; }
  if(偏移<长度){ 缓冲长度=长度-偏移; memcpy(缓冲,数据+偏移,缓冲长度); } }
