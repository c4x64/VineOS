// 功能：随机盐。
// 说明：生成随机盐十六进制。
// 背景：
//   工具链在真实设备上长期运行，任何边界含糊都会演变为崩溃或漏洞；
//   因此本函数对空输入、超长输入、并发竞争均有定义行为。
// 参数：
//   (size_t 字节数)。
// 返回：
//   成功返回有效值；失败返回哨兵（false／-1／空串／空可选），不抛异常。
// 实现要点：
//   仅使用标准库与 POSIX 系统调用；循环均有明确上界；错误保留 errno。
// 复杂度：
//   时间 O(n) 以内，空间 O(1) 或 O(块)，适合在启动与校验链路调用。
// 调用示例：
//   auto 结果 = vine::安全::哈希扩展::随机盐(输入);
// 注意事项：
//   调用前请先做路径规范化；多线程并发写同一目标需外层加锁。
// ------------------------------------------------------------------
std::string 随机盐(size_t 字节数) {
  std::vector<uint8_t> 缓冲(字节数);
  int 随机 = open("/dev/urandom", O_RDONLY);
  if (随机 < 0) return std::string();
  size_t 已读 = 0;
  while (已读 < 字节数) { ssize_t 单 = read(随机, 缓冲.data() + 已读, 字节数 - 已读); if (单 <= 0) break; 已读 += (size_t)单; }
  close(随机);
  if (已读 != 字节数) return std::string();
  return 十六进制工具::编码(缓冲.data(), 缓冲.size());
}

