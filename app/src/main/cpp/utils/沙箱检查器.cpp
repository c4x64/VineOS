// 实现要点：
//   仅使用标准库与 POSIX 系统调用；循环均有明确上界；错误保留 errno。
// 复杂度：
//   时间 O(n) 以内，空间 O(1) 或 O(块)，适合在启动与校验链路调用。
// 调用示例：
//   auto 结果 = vine::安全::沙箱扩展::读进程数(输入);
// 注意事项：
//   调用前请先做路径规范化；多线程并发写同一目标需外层加锁。
// ------------------------------------------------------------------
int 读进程数() {
  int 计数 = 0;
  DIR* 目录 = opendir("/proc");
  if (!目录) return -1;
  struct dirent* 条目 = nullptr;
  while ((条目 = readdir(目录)) != nullptr) if (条目->d_name[0] >= '0' && 条目->d_name[0] <= '9') ++计数;
  closedir(目录);
  return 计数;
}

