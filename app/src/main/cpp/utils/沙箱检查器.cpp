// 挂载表缓存：综合检查内连调 统计可写／危险挂载／沙箱挂载 等多次读取
// /proc/self/mounts，缓存 1000ms 复用单次解析结果，跨调用省 N-1 次 I/O。
// 线程安全：互斥守卫，读命中仅一次时钟调用。
namespace 挂载缓存区 {
static std::mutex 锁;
static long 缓存时刻 = 0;
static std::vector<挂载条目> 缓存表;
static long 单调毫秒() { struct timespec 时间{}; clock_gettime(CLOCK_MONOTONIC, &时间); return (long)(时间.tv_sec * 1000L + 时间.tv_nsec / 1000000L); }
static bool 取缓存(std::vector<挂载条目>& 输出) {
  std::lock_guard<std::mutex> 守卫(锁);
  if (缓存时刻 != 0 && 单调毫秒() - 缓存时刻 < 1000 && !缓存表.empty()) { 输出 = 缓存表; return true; }
  return false;
}
static void 存缓存(const std::vector<挂载条目>& 表) {
  std::lock_guard<std::mutex> 守卫(锁);
  缓存表 = 表; 缓存时刻 = 单调毫秒();
}
}  // namespace 挂载缓存区

// 命名空间种类表：检查命名空间隔离／取隔离计数／网络挂载进程三包装共用，
// 新增种类只改此表，不复制函数体。
static const char* 命名空间种类表[] = {"mnt", "pid", "net", "uts", "ipc"};
static const size_t 命名空间种类数 = sizeof(命名空间种类表) / sizeof(命名空间种类表[0]);

// 读取挂载表：解析 /proc/self/mounts，每行取前四列。
std::vector<挂载条目> 沙箱检查器::读取挂载表() {
  std::vector<挂载条目> 缓存命中;
  if (挂载缓存区::取缓存(缓存命中)) return 缓存命中;
  std::vector<挂载条目> 结果; 结果.reserve(32); FILE* 文件=fopen("/proc/self/mounts","r"); if(!文件) return 结果;
  char 设备[512],点[512],类型[128],选项[1024];
  while(fscanf(文件,"%511s %511s %127s %1023s %*d %*d",设备,点,类型,选项)==4){ 挂载条目 条; 条.设备=设备; 条.挂载点=点; 条.类型=类型; 条.选项=选项; 结果.push_back(条); }
  fclose(文件); 挂载缓存区::存缓存(结果); return 结果; }

// 挂载点只读：查挂载表选项是否含 ro。
bool 沙箱检查器::挂载点只读(const std::string& 挂载点) { for(auto& 条:读取挂载表()){ if(条.挂载点==挂载点){ return 条.选项.find("ro")!=std::string::npos; } } struct stat 缓冲{}; if(stat(挂载点.c_str(),&缓冲)!=0) return false; return access(挂载点.c_str(),W_OK)!=0; }
// 路径可写：access 探测。
bool 沙箱检查器::路径可写(const std::string& 路径) { return access(路径.c_str(),W_OK)==0; }

// 读状态字段：从 /proc/pid/status 提取指定行。
std::optional<std::string> 沙箱检查器::读状态字段(pid_t 进程, const std::string& 字段) {
  std::string 路径="/proc/"+std::to_string((long)进程)+"/status"; FILE* 文件=fopen(路径.c_str(),"r"); if(!文件) return std::nullopt;
  char 行[1024]; std::optional<std::string> 结果;
  while(fgets(行,sizeof(行),文件)){ if(strncmp(行,字段.c_str(),字段.size())==0){ 结果=std::string(行); break; } }
  fclose(文件); return 结果; }

// 读命名空间链接：readlink /proc/pid/ns/种类。
std::string 沙箱检查器::读命名空间链接(pid_t 进程, const std::string& 种类) {
  std::string 路径="/proc/"+std::to_string((long)进程)+"/ns/"+种类; char 缓冲[256]; ssize_t 长度=readlink(路径.c_str(),缓冲,sizeof(缓冲)-1); if(长度<0) return ""; 缓冲[长度]='\0'; return std::string(缓冲); }
bool 沙箱检查器::同一命名空间(pid_t 甲, pid_t 乙, const std::string& 种类) { std::string 甲链=读命名空间链接(甲,种类),乙链=读命名空间链接(乙,种类); return !甲链.empty()&&甲链==乙链; }

// 检查命名空间隔离：自身与 1 号进程的 mount/pid/net 任一不同即隔离。
