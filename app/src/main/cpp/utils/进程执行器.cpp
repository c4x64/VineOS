// 在路径中查找：在每个目录下拼接候选并检查可执行位；含斜杠直接校验。
// 缓存命中零系统调用；缺失同样缓存，避免恶意循环反复 stat。
std::optional<std::string> 进程执行器::在路径中查找(const std::string& 命令名, const std::string& 路径表) {
  if(命令名.empty()||命令名.find('\0')!=std::string::npos) return std::nullopt;
  if(命令名.find('/')!=std::string::npos) { if(是否可执行文件(命令名)) return 命令名; return std::nullopt; }
  std::string 表 = 路径表.empty()?取默认路径表():路径表;
  std::string 缓存值; bool 有值 = false;
  if (路径缓存区::取缓存(命令名, 表, 缓存值, 有值)) { if (有值) return 缓存值; return std::nullopt; }
  for(auto& 目录:切分路径表(表)) { std::string 候选; 候选.reserve(目录.size()+命令名.size()+1); 候选+=目录; 候选+='/'; 候选+=命令名; if(是否可执行文件(候选)) { 路径缓存区::存缓存(表, 命令名, 候选, true); return 候选; } }
  路径缓存区::存缓存(表, 命令名, std::string(), false);
  return std::nullopt; }

