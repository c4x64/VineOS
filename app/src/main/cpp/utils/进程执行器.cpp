// PATH 查找缓存：解析可执行路径是每次执行的前置热路径，旧实现每调用
// 触发 getenv＋切分＋逐目录 stat＋access；现缓存 PATH 快照＋命中表，
// 同 PATH 下重复命令零系统调用命中；PATH 变化自动失效重建。
// 线程安全：互斥守卫；负命中以空串标记，避免重复 stat 缺失命令。
namespace 路径缓存区 {
static std::mutex 锁;
static std::string 缓存路径表;
static std::unordered_map<std::string, std::string> 命中表;
static bool 取缓存(const std::string& 命令名, const std::string& 路径表, std::string& 输出, bool& 有值) {
  std::lock_guard<std::mutex> 守卫(锁);
  if (缓存路径表 != 路径表) return false;
  auto 找 = 命中表.find(命令名);
  if (找 == 命中表.end()) return false;
  有值 = !找->second.empty();
  输出 = 找->second;
  return true;
}
static void 存缓存(const std::string& 路径表, const std::string& 命令名, const std::string& 值, bool 有值) {
  std::lock_guard<std::mutex> 守卫(锁);
  if (缓存路径表 != 路径表) { 缓存路径表 = 路径表; 命中表.clear(); }
  if (命中表.size() > 512) 命中表.clear();
  命中表[命令名] = 有值 ? 值 : std::string();
}
}  // namespace 路径缓存区

