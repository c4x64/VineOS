// 大数比较：先比有效长度，再逐字节字典序。
int 大数工具::比较(const std::vector<uint8_t>& 甲, const std::vector<uint8_t>& 乙) { auto 甲去=去前导零(甲),乙去=去前导零(乙); if(甲去.size()!=乙去.size()) return 甲去.size()<乙去.size()?-1:1; for(size_t i=0;i<甲去.size();++i){ if(甲去[i]!=乙去[i]) return 甲去[i]<乙去[i]?-1:1; } return 0; }
std::vector<uint8_t> 大数工具::去前导零(const std::vector<uint8_t>& 值) { size_t i=0; while(i<值.size()&&值[i]==0) ++i; if(i==值.size()) return std::vector<uint8_t>{0}; return std::vector<uint8_t>(值.begin()+i,值.end()); }
bool 大数工具::为零(const std::vector<uint8_t>& 值) { for(auto 字节:值) if(字节) return false; return true; }
size_t 大数工具::位长度(const std::vector<uint8_t>& 值) { auto 去=去前导零(值); if(去.size()==1&&去[0]==0) return 0; size_t 位=(去.size()-1)*8; uint8_t 首=去[0]; while(首){ ++位; 首>>=1; } return 位; }
bool 大数工具::测试位(const std::vector<uint8_t>& 值, size_t 位) { size_t 字节位=位/8; size_t 偏移=位%8; if(字节位>=值.size()) return false; return (值[值.size()-1-字节位]>>偏移)&1; }
std::vector<uint8_t> 大数工具::左移一位(const std::vector<uint8_t>& 值) { std::vector<uint8_t> 结果(值.size()+1,0); uint8_t 进位=0; for(size_t i值=值.size();i值>0;--i值){ size_t i=i值-1; uint8_t 新进=(值[i]&0x80)?1:0; 结果[i+1]=(uint8_t)((值[i]<<1)|进位); 进位=新进; } 结果[0]=进位; return 去前导零(结果); }
std::vector<uint8_t> 大数工具::减法(const std::vector<uint8_t>& 甲, const std::vector<uint8_t>& 乙) { size_t 长度=甲.size()>乙.size()?甲.size():乙.size(); std::vector<uint8_t> 甲扩(长度,0),乙扩(长度,0); for(size_t i=0;i<甲.size();++i) 甲扩[长度-甲.size()+i]=甲[i]; for(size_t i=0;i<乙.size();++i) 乙扩[长度-乙.size()+i]=乙[i]; std::vector<uint8_t> 结果(长度,0); int 借位=0; for(size_t k=长度;k>0;--k){ size_t i=k-1; int 差=(int)甲扩[i]-(int)乙扩[i]-借位; if(差<0){差+=256;借位=1;} else 借位=0; 结果[i]=(uint8_t)差; } return 去前导零(结果); }
std::vector<uint8_t> 大数工具::取模(const std::vector<uint8_t>& 值, const std::vector<uint8_t>& 模数) { auto 余=去前导零(值),模=去前导零(模数); if(比较(余,模)<0) return 余; size_t 移位=位长度(余)-位长度(模); auto 除数=模; for(size_t i=0;i<移位;++i) 除数=左移一位(除数); for(size_t i=0;i<=移位;++i){ if(比较(余,除数)>=0) 余=减法(余,除数); if(i==移位) break; std::vector<uint8_t> 半(除数.size(),0); uint8_t 借=0; for(size_t k=除数.size();k>0;--k){ size_t j=k-1; uint8_t 新借=(除数[j]&1)?0x80:0; 半[j]=(uint8_t)((除数[j]>>1)|借); 借=新借; } 除数=去前导零(半); } return 余; }
std::vector<uint8_t> 大数工具::模乘(const std::vector<uint8_t>& 甲, const std::vector<uint8_t>& 乙, const std::vector<uint8_t>& 模数) { auto 甲余=取模(甲,模数); std::vector<uint8_t> 结果{0}; auto 基=甲余; auto 乘=去前导零(乙); for(size_t 位=0;位<位长度(乘);++位){ if(测试位(乘,位)){ std::vector<uint8_t> 和(结果.size()>基.size()?结果.size()+1:基.size()+1,0); size_t 长度=和.size(); std::vector<uint8_t> 甲扩(长度,0),乙扩(长度,0); for(size_t i=0;i<结果.size();++i) 甲扩[长度-结果.size()+i]=结果[i]; for(size_t i=0;i<基.size();++i) 乙扩[长度-基.size()+i]=基[i]; unsigned 进位=0; for(size_t k=长度;k>0;--k){ size_t i=k-1; unsigned 和值=(unsigned)甲扩[i]+(unsigned)乙扩[i]+进位; 和[i]=(uint8_t)(和值&0xFF); 进位=和值>>8; } 结果=取模(去前导零(和),模数); } 基=取模(左移一位(基),模数); } return 结果; }
std::vector<uint8_t> 大数工具::模幂(const std::vector<uint8_t>& 底, const std::vector<uint8_t>& 指数, const std::vector<uint8_t>& 模数) { std::vector<uint8_t> 结果{1}; auto 基=取模(底,模数); size_t 位数=位长度(指数); for(size_t 位=0;位<位数;++位){ if(测试位(指数,位)) 结果=模乘(结果,基,模数); 基=模乘(基,基,模数); } return 结果; }

// Base64 解码：支持标准字母表与等号填充，忽略换行。
std::optional<std::vector<uint8_t>> 签名校验器::解码_base64(const std::string& 文本) {
  auto 值=[](char 字符)->int{ if(字符>='A'&&字符<='Z') return 字符-'A'; if(字符>='a'&&字符<='z') return 字符-'a'+26; if(字符>='0'&&字符<='9') return 字符-'0'+52; if(字符=='+') return 62; if(字符=='/') return 63; return -1; };
  std::string 干净; for(char 字符:文本){ if(字符=='\r'||字符=='\n'||字符==' '||字符=='\t') continue; 干净+=字符; }
  if(干净.size()%4) return std::nullopt; std::vector<uint8_t> 结果;
  for(size_t i=0;i<干净.size();i+=4){ int 甲=值(干净[i]),乙=值(干净[i+1]); int 丙=干净[i+2]=='='?-2:值(干净[i+2]),丁=干净[i+3]=='='?-2:值(干净[i+3]); if(甲<0||乙<0||丙<-1||丁<-1) return std::nullopt; if(丙==-2&&丁==-2){ if(i+4!=干净.size()) return std::nullopt; 结果.push_back((uint8_t)((甲<<2)|(乙>>4))); } else if(丁==-2){ 结果.push_back((uint8_t)((甲<<2)|(乙>>4))); 结果.push_back((uint8_t)(((乙&15)<<4)|(丙>>2))); } else { 结果.push_back((uint8_t)((甲<<2)|(乙>>4))); 结果.push_back((uint8_t)(((乙&15)<<4)|(丙>>2))); 结果.push_back((uint8_t)(((丙&3)<<6)|丁)); } }
  return 结果; }
// DER 长度解析：短式单字节，长式多字节大端。
std::optional<std::vector<uint8_t>> 签名校验器::解析_der_长度(const uint8_t* 数据, size_t 长度, size_t& 偏移, size_t& 内容长) {
  if(偏移>=长度) return std::nullopt; uint8_t 首=数据[偏移++]; if(!(首&0x80)){ 内容长=首; return std::vector<uint8_t>(); }
  size_t 字节数=首&0x7F; if(!字节数||字节数>4||偏移+字节数>长度) return std::nullopt; 内容长=0; for(size_t i=0;i<字节数;++i){ 内容长=(内容长<<8)|数据[偏移++]; } return std::vector<uint8_t>(); }
// PEM 公钥解析：验头尾→Base64→SEQUENCE→BIT STRING→模数指数。
std::optional<公钥> 签名校验器::解析_pem_公钥(const std::string& 文本) {
  公钥 钥匙; if(!校验_pem_头尾(文本)) return std::nullopt;
  size_t 头=文本.find("-----BEGIN PUBLIC KEY-----"); size_t 尾=文本.find("-----END PUBLIC KEY-----"); if(头==std::string::npos||尾==std::string::npos) return std::nullopt;
  std::string 中间=文本.substr(头+26,尾-(头+26)); auto 二进制=解码_base64(中间); if(!二进制.has_value()) return std::nullopt;
  const auto& 数据=*二进制; if(!校验_der_结构(数据)) return std::nullopt;
  size_t 偏移=0; if(数据[偏移++]!=0x30) return std::nullopt; size_t 外长=0; if(!解析_der_长度(数据.data(),数据.size(),偏移,外长).has_value()) return std::nullopt;
  if(偏移+外长!=数据.size()) return std::nullopt;
  size_t 位串位=0; for(;偏移<数据.size();++偏移){ if(数据[偏移]==0x03){ size_t 串长=0; size_t 记=偏移+1; if(!解析_der_长度(数据.data(),数据.size(),记,串长).has_value()) continue; if(记<数据.size()&&数据[记]==0x00&&记+1+串长-1<=数据.size()){ 位串位=记+1; break; } } }
  if(!位串位) return std::nullopt; size_t 内=位串位; if(数据[内++]!=0x30) return std::nullopt; size_t 内长=0; if(!解析_der_长度(数据.data(),数据.size(),内,内长).has_value()) return std::nullopt;
  if(数据[内++]!=0x02) return std::nullopt; size_t 模长=0; if(!解析_der_长度(数据.data(),数据.size(),内,模长).has_value()) return std::nullopt; if(内+模长>数据.size()) return std::nullopt;
  钥匙.模数=std::vector<uint8_t>(数据.begin()+内,数据.begin()+内+模长); 内+=模长;
  if(内>=数据.size()||数据[内++]!=0x02) return std::nullopt; size_t 指长=0; if(!解析_der_长度(数据.data(),数据.size(),内,指长).has_value()) return std::nullopt; if(内+指长>数据.size()) return std::nullopt;
  钥匙.指数=std::vector<uint8_t>(数据.begin()+内,数据.begin()+内+指长); 钥匙.有效=true; return 钥匙; }
// PKCS#1 v1.5 填充校验：00 01 FF.. 00 ＋ DigestInfo(SHA256) ＋ 摘要。
bool 签名校验器::校验_pkcs1_填充(const std::vector<uint8_t>& 解密, const std::vector<uint8_t>& 摘要) {
  static const uint8_t 头部[]={0x30,0x31,0x30,0x0d,0x06,0x09,0x60,0x86,0x48,0x01,0x65,0x03,0x04,0x02,0x01,0x05,0x00,0x04,0x20};
  if(解密.size()<2+sizeof(头部)+摘要.size()+11) return false; if(解密[0]!=0x00||解密[1]!=0x01) return false;
  size_t 位置=2; while(位置<解密.size()&&解密[位置]==0xFF) ++位置; if(位置-2<8) return false; if(位置>=解密.size()||解密[位置++]!=0x00) return false;
  if(位置+sizeof(头部)>解密.size()||memcmp(解密.data()+位置,头部,sizeof(头部))!=0) return false; 位置+=sizeof(头部);
  if(位置+摘要.size()!=解密.size()||memcmp(解密.data()+位置,摘要.data(),摘要.size())!=0) return false; return true; }
// SHA256withRSA 主校验：模幂解密→填充校验。
签名结果 签名校验器::校验_沙256_rsa(const std::vector<uint8_t>& 消息, const std::vector<uint8_t>& 签名, const 公钥& 钥匙) {
  签名结果 结果; if(!钥匙.有效){ 结果.错误描述="公钥无效"; return 结果; }
  if(!校验签名长度(签名,钥匙)){ 结果.错误描述="签名长度与模数不一致"; return 结果; }
  auto 模去=大数工具::去前导零(钥匙.模数); auto 解密=大数工具::模幂(签名,钥匙.指数,模去);
  std::vector<uint8_t> 定长(模去.size(),0); auto 去=大数工具::去前导零(解密); if(去.size()>定长.size()){ 结果.错误描述="解密超长"; return 结果; } for(size_t i=0;i<去.size();++i) 定长[定长.size()-去.size()+i]=去[i];
  沙256上下文 上下文; if(!消息.empty()) 上下文.更新(消息.data(),消息.size()); auto 摘要=上下文.终结();
  结果.摘要十六进制=十六进制工具::编码(摘要.data(),摘要.size());
  结果.通过=校验_pkcs1_填充(定长,摘要); if(!结果.通过) 结果.错误描述="填充或摘要不匹配"; return 结果; }
签名结果 签名校验器::校验文件_沙256_rsa(const std::string& 文件路径, const std::vector<uint8_t>& 签名, const 公钥& 钥匙) {
  签名结果 结果;
  if (!钥匙.有效) { 结果.错误描述 = "公钥无效"; return 结果; }
  if (!校验签名长度(签名, 钥匙)) { 结果.错误描述 = "签名长度与模数不一致"; return 结果; }
  // 单遍流式：边读边喂 SHA256 上下文，峰值内存恒定 64K；
  // 旧实现先整文件哈希再整文件读入内存（两遍 I/O＋O(n) 堆），大包必爆内存。
  int 描述符 = open(文件路径.c_str(), O_RDONLY);
  if (描述符 < 0) { 结果.错误描述 = std::string("打开失败：") + strerror(errno); return 结果; }
  struct stat 缓冲{};
  if (fstat(描述符, &缓冲) != 0) { 结果.错误描述 = "状态获取失败"; close(描述符); return 结果; }
  if (!S_ISREG(缓冲.st_mode)) { 结果.错误描述 = "非普通文件"; close(描述符); return 结果; }
  if (缓冲.st_size > 512L * 1024 * 1024) { 结果.错误描述 = "文件过大拒绝验签"; close(描述符); return 结果; }
  沙256上下文 上下文;
  uint8_t 块[65536];
  while (true) {
    ssize_t 已读 = read(描述符, 块, sizeof(块));
    if (已读 < 0) { if (errno == EINTR) continue; 结果.错误描述 = "读取失败"; close(描述符); return 结果; }
    if (已读 == 0) break;
    上下文.更新(块, (size_t)已读);
  }
  close(描述符);
  auto 摘要 = 上下文.终结();
  结果.摘要十六进制 = 十六进制工具::编码(摘要.data(), 摘要.size());
  auto 模去 = 大数工具::去前导零(钥匙.模数);
  auto 解密 = 大数工具::模幂(签名, 钥匙.指数, 模去);
  std::vector<uint8_t> 定长(模去.size(), 0);
  auto 去 = 大数工具::去前导零(解密);
  if (去.size() > 定长.size()) { 结果.错误描述 = "解密超长"; return 结果; }
  for (size_t i = 0; i < 去.size(); ++i) 定长[定长.size() - 去.size() + i] = 去[i];
  结果.通过 = 校验_pkcs1_填充(定长, 摘要);
  if (!结果.通过) 结果.错误描述 = "填充或摘要不匹配";
  return 结果;
}
