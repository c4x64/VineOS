// 词法规范化：折叠重复斜杠、消解 . 与 ..，不触碰文件系统。
// 算法：按 / 切分压栈，遇 .. 弹栈（栈空则保留以便上层拒绝），最后重组。
// 参数：路径 —— 原始输入；含点段 —— 输出是否见过 . 或 ..。
// 返回：规范后的词法路径（相对仍相对，绝对仍绝对）。
std::string 路径规范化器::词法规范化(const std::string& 路径, bool* 含点段) {
  bool 见点 = false;
  bool 绝对 = !路径.empty() && 路径[0] == '/';
  std::vector<std::string> 栈;
  栈.reserve(16);
  std::string 当前;
  当前.reserve(64);
  auto 推段 = [&](const std::string& 段) {
    if (段.empty() || 段 == ".") { if (段 == ".") 见点 = true; return; }
    if (段 == "..") { 见点 = true; if (!栈.empty() && 栈.back() != "..") 栈.pop_back(); else if (!绝对) 栈.push_back(".."); return; }
    栈.push_back(段);
  };
  for (size_t i = 0; i <= 路径.size(); ++i) {
    if (i == 路径.size() || 路径[i] == '/') { 推段(当前); 当前.clear(); } else 当前 += 路径[i];
  }
  std::string 结果 = 合并路径(栈, 绝对);
  if (含点段) *含点段 = 见点;
  return 结果.empty() ? (绝对 ? std::string("/") : std::string(".")) : 结果;
}

// 消解链接：优先 realpath，失败回退词法规范化，保证总有可用结果。
std::optional<std::string> 路径规范化器::消解链接(const std::string& 路径, size_t 最大跳数) {
  (void)最大跳数;
  char* 实 = realpath(路径.c_str(), nullptr);
  if (实) { std::string 结果(实); free(实); return 结果; }
  if (errno == ENOENT) return 词法规范化(路径);
  return std::nullopt;
}

// 规范化主入口：先做长度与空值检查，再词法折叠，必要时 realpath 消解。
规范化结果 路径规范化器::规范化(const std::string& 原始路径, const 规范化选项& 选项) {
  规范化结果 结果;
  if (选项.拒绝空路径 && 原始路径.empty()) { 结果.错误描述 = "路径为空"; return 结果; }
  if (原始路径.size() >= 选项.最大长度) { 结果.错误描述 = "路径过长"; return 结果; }
  if (原始路径.find('\0') != std::string::npos) { 结果.错误描述 = "路径含空字节"; return 结果; }
  bool 含点 = false;
  std::string 词法 = 词法规范化(原始路径, &含点);
  结果.曾含点段 = 含点;
  if (选项.消解符号链接) {
    auto 消解 = 消解链接(词法, 选项.最大链接跳数);
    if (消解.has_value()) { 结果.规范路径 = *消解; 结果.曾含链接 = (*消解 != 词法); }
    else if (!选项.必须存在) { 结果.规范路径 = 词法; }
    else { 结果.错误描述 = std::string("消解失败：") + strerror(errno); return 结果; }
  } else { 结果.规范路径 = 词法; }
  结果.成功 = true;
  return 结果;
}

