std::string 取公共父目录(const std::vector<std::string>& 列表) {
  if (列表.empty()) return std::string("/");
  std::string 公共 = 路径规范化器::词法规范化(列表[0]);
  for (size_t i = 1; i < 列表.size(); ++i) {
    std::string 当前 = 路径规范化器::词法规范化(列表[i]);
    size_t 共同 = 路径规范化器::共同前缀长(公共, 当前);
    公共 = 公共.substr(0, 共同);
  }
  size_t 斜 = 公共.find_last_of('/');
  if (斜 == std::string::npos) return std::string("/");
  return 公共.substr(0, 斜 == 0 ? 1 : 斜);
}

