    bool 启用回环接口(const std::string &命名空间路径);
    bool 禁用回环接口(const std::string &命名空间路径);
    bool 配置容器地址(const std::string &接口名称, const std::string &地址文本, int 前缀长度);
    bool 配置主机地址(const std::string &接口名称, const std::string &地址文本, int 前缀长度);
    bool 接入容器网桥(const std::string &接口名称, const std::string &网桥名称);
    bool 创建容器网桥(const std::string &网桥名称);
    bool 删除容器网桥(const std::string &网桥名称);
    bool 开启地址转发();
    bool 关闭地址转发();
    bool 读取转发状态();
    bool 写入域名解析(const std::string &根路径, const std::string &域名文本);
    std::string 读取域名解析(const std::string &根路径);
    bool 移动接口到容器(const std::string &接口名称, int 容器进程);
    bool 查询接口存在(const std::string &接口名称);
    bool 查询接口启用(const std::string &接口名称);
    int 查询接口索引(const std::string &接口名称);
    std::string 查询接口地址(const std::string &接口名称);
    std::string 查询接口掩码(const std::string &接口名称);
    long 查询接收字节(const std::string &接口名称);
    long 查询发送字节(const std::string &接口名称);
    long 查询接收包数(const std::string &接口名称);
    long 查询发送包数(const std::string &接口名称);
    long 查询接收错误(const std::string &接口名称);
    long 查询发送错误(const std::string &接口名称);
    long 查询接收丢弃(const std::string &接口名称);
    long 查询发送丢弃(const std::string &接口名称);
    bool 添加默认路由(const std::string &网关地址, const std::string &接口名称);
    bool 删除默认路由(const std::string &接口名称);
    std::string 查询默认路由();
    bool 设置最大传输单元(const std::string &接口名称, int 单元值);
    int 查询最大传输单元(const std::string &接口名称);
    bool 启用接口混杂(const std::string &接口名称);
    bool 禁用接口混杂(const std::string &接口名称);
    bool 绑定命名空间文件(const std::string &实例标识, int 进程标识);
    bool 解绑命名空间文件(const std::string &实例标识);
    bool 比较命名空间隔离(int 容器进程);
    std::string 读取宿主命名空间();
    std::string 读取容器命名空间(int 容器进程);
    bool 执行隔离子进程(const std::string &实例标识, const std::vector<std::string> &命令参数);
    bool 配置容器全栈网络(const std::string &实例标识, int 容器进程, const std::string &根路径);
    bool 清理容器网络(const std::string &实例标识);
    std::string 导出网络诊断();
    std::string 读取实例标识();
    std::string 读取网桥名称();
    void 设置网桥名称(const std::string &网桥文本);
    std::string 读取主机端名前缀();
    std::string 读取容器端名();
    std::string 生成接口名称(const std::string &实例标识, bool 是否主机端);
    bool 校验地址文本(const std::string &地址文本);
    bool 校验前缀长度(int 前缀长度);
    bool 校验接口名称(const std::string &接口名称);
    bool 执行命令行工具(const std::vector<std::string> &命令参数);
    bool 查询工具可用(const std::string &工具名称);
    bool 添加防火墙规则(const std::string &规则文本);
    bool 删除防火墙规则(const std::string &规则文本);
    bool 清空防火墙规则(const std::string &表名);
    bool 记录网络事件(const std::string &事件文本);
    long 读取事件计数();
    void 清空事件计数();
    long 查询在线接口数();
    long 查询网桥成员数(const std::string &网桥名称);
