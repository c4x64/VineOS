namespace vine {

// 资源配额：描述单个容器的期望限制。
struct 资源配额 {
    std::string 实例标识;
    int 内存兆字节 = 1024;
    int 处理器核数 = 0;
    int 块设备权重 = 500;
    long 进程数上限 = 512;
    std::string 处理器亲和掩码;
};

// 资源调度器：统一管理控制组配额与进程调度属性。
class 资源调度器 {
public:
    资源调度器();
    ~资源调度器();
    资源调度器(const 资源调度器 &) = delete;
    资源调度器 &operator=(const 资源调度器 &) = delete;

    bool 应用全部配额(const std::string &实例标识, int 进程标识, int 内存兆字节, int 处理器核数);
    bool 应用内存上限(const std::string &实例标识, int 内存兆字节);
    bool 应用处理器配额(const std::string &实例标识, int 处理器核数);
    bool 应用块设备权重(const std::string &实例标识, int 权重值);
    bool 应用进程数上限(const std::string &实例标识, long 上限数);
    bool 设置处理器亲和(int 进程标识, const std::string &掩码文本);
    bool 提升前台优先级(int 进程标识);
    bool 恢复后台优先级(int 进程标识);
    bool 冻结容器(const std::string &实例标识);
    bool 解冻容器(const std::string &实例标识);
    long 查询内存上限(const std::string &实例标识);
    long 查询处理器配额(const std::string &实例标识);
    std::string 查询冻结状态(const std::string &实例标识);
    bool 移除资源分组(const std::string &实例标识);
    std::string 导出调度诊断();
    std::string 读取分组标签();
    void 设置分组标签(const std::string &标签文本);
    int 读取内存兆字节();
    int 读取处理器核数();
    bool 应用大页内存上限(const std::string &实例标识, long 上限字节);
    bool 应用交换上限(const std::string &实例标识, int 兆字节);
    bool 应用处理器权重(const std::string &实例标识, int 权重值);
    bool 应用输入输出上限(const std::string &实例标识, long 每秒字节);
    bool 限制文件描述符数(int 进程标识, long 上限数);
    bool 设置调度策略(int 进程标识, int 策略编号);
    long 查询处理器权重(const std::string &实例标识);
    long 查询进程数上限(const std::string &实例标识);
    long 查询块设备权重(const std::string &实例标识);
    long 查询大页上限(const std::string &实例标识);
    bool 绑定分组进程(const std::string &实例标识, int 进程标识);
    bool 迁移分组进程(const std::string &来源标识, const std::string &目标标识);
    bool 创建资源分组(const std::string &实例标识);
    void 清理全部资源分组();
    bool 读取统一层级标志();
    bool 刷新统一层级标志();
    bool 写入统一层级文件(const std::string &相对路径, const std::string &写入内容);
    std::string 读取统一层级文件(const std::string &相对路径);
    bool 写入分离层级文件(const std::string &控制器名, const std::string &文件名, const std::string &写入内容);
    std::string 读取分离层级文件(const std::string &控制器名, const std::string &文件名);
    bool 校验内存合法(int 内存兆字节);
    bool 校验核数合法(int 处理器核数);
    std::string 换算配额文本(int 处理器核数);
    int 解析配额文本(const std::string &配额文本);
    std::string 查询在线掩码();
    bool 校验亲和掩码(const std::string &掩码文本);
    bool 等待冻结生效(const std::string &分组路径, int 超时毫秒);
    bool 等待解冻生效(const std::string &分组路径, int 超时毫秒);
    long 读取系统内存总量();
    long 读取系统可用内存();
    long 读取系统核数();
    int 估算合理内存(int 请求兆字节);
    int 估算合理核数(int 请求核数);
    bool 记录调度事件(const std::string &事件文本);
    long 读取事件计数();
    void 清空事件计数();
private:
    std::mutex 互斥锁;
    std::string 分组标签{"默认分组"};
    int 内存兆字节_ = 1024;
    int 处理器核数_ = 0;
    long 事件计数 = 0;
    bool 统一层级 = true;
    std::vector<std::string> 已创建分组;
    std::string 短名(const std::string &实例标识);
    std::string 统一分组(const std::string &实例标识);
    bool 写入统一文件(const std::string &实例标识, const char *文件名, const std::string &内容);
    long 读取统一整数(const std::string &实例标识, const char *文件名);
    std::string 读取统一文本(const std::string &实例标识, const char *文件名);
    bool 写入分组值(const std::string &实例标识, const char *统一名, const char *控制器, const char *分离名, const std::string &内容);
    long 读取分组整数(const std::string &实例标识, const char *统一名, const char *控制器, const char *分离名);
    bool 校验进程存活(int 进程标识);
    bool 等待冻结状态(const std::string &分组路径, bool 期望冻结, int 超时毫秒);
};

} // namespace vine
