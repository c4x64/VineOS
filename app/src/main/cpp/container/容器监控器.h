// 容器资源快照：一次采集的完整数值集合。
struct 容器资源快照 {
    std::string 实例标识;
    int 进程标识 = -1;
    long 处理器用户态 = 0;
    long 处理器内核态 = 0;
    long 处理器空闲态 = 0;
    long 内存使用字节 = 0;
    long 内存上限字节 = 0;
    long 块读字节 = 0;
    long 块写字节 = 0;
    long 网络接收字节 = 0;
    long 网络发送字节 = 0;
    long 线程数量 = 0;
    long 采集时刻毫秒 = 0;
};

// 容器监控器：后台线程周期采集 proc 与控制组指标。
