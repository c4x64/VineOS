    int 读取采集间隔();
    void 记录丢弃计数();
    long 读取丢弃计数();
    bool 写入原始字节(const char *数据指针, long 数据长度);
    long 读取内核环形大小();
    bool 设置内核环形大小(long 大小字节);
    bool 压缩历史日志();
    bool 清理过期日志(int 保留天数);
    long 统计日志总字节();
    long 统计日志文件数();
    bool 校验目录可写();
    bool 创建日志目录(const std::string &目录路径);
    std::string 生成时间戳文本();
    std::string 格式化条目文本(const std::string &级别文本, const std::string &条目文本);
    int 解析级别权重(const std::string &级别文本);
    std::string 过滤级别记录(const std::string &最低级别, int 最近条数);
    void 设置最低级别(const std::string &级别文本);
    std::string 读取最低级别();
    void 后台采集循环();
    bool 采集单轮数据();
    bool 写入启动横幅(const std::string &实例标识);
    bool 写入停止横幅();
    long 读取刷盘次数();
    long 读取写入条数();
    long 读取轮转次数();
    bool 检查文件描述符有效();
    bool 重新打开日志文件();
