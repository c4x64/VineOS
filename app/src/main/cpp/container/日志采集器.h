    bool 采集内存信息();
    bool 采集挂载信息();
    bool 采集网络信息();
    bool 启动采集线程();
    void 停止采集线程();
    bool 正在采集();
    bool 刷盘缓冲();
    void 清空环形缓冲();
    long 读取缓冲条数();
    std::string 读取最近记录(int 最近条数);
    std::string 读取全部记录();
    std::string 导出采集诊断();
    std::string 读取实例标识();
    std::string 读取目录路径();
    std::string 读取文件路径();
