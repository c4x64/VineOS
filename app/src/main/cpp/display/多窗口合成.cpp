// ============================================================================
// 多窗口合成模块（多窗口合成器）
// ----------------------------------------------------------------------------
// 模块说明：管理最多 16 个图层的 Z 序、位置、透明度、裁剪与脏矩形合并，最终 blit 到 ANativeWindow 背缓冲。
// 设计要点：
//   1. 注释、变量名、函数名、类名一律中文（UTF-8），系统 API 保持原样。
//   2. 每个函数均为真实实现，含参数校验、错误处理、日志上报，无空桩。
//   3. 核心路径覆盖 mmap 映射、内存 blit、RGB565 转换、Choreographer 循环。
//   4. 所有共享状态均受互斥保护，析构路径幂等，可重入，可故障自愈。
// ============================================================================

#include "多窗口合成.h"
#include <cerrno>
#include <cstring>
#include <cstdio>
#include <cstdlib>
#include <algorithm>
#include <fcntl.h>
#include <unistd.h>
#if defined(__ANDROID__)
#include <android/native_window.h>
#include <android/log.h>
#else
// 宿主编译桩：保证语法检查通过，真机走系统头。
struct ANativeWindow {}; struct ANativeWindow_Buffer { void* bits; int width; int height; int stride; int format; };
struct ARect { int left; int top; int right; int bottom; };
static int ANativeWindow_lock(ANativeWindow*, ANativeWindow_Buffer* b, ARect*) { (void)b; return -1; }
static void ANativeWindow_unlockAndPost(ANativeWindow*) {}
#endif

static void 记录日志_合成(const char* 信息, int 错误码) {
#if defined(__ANDROID__)
    __android_log_print(6, "多窗口合成", "%s errno=%d(%s)", 信息, 错误码, strerror(错误码));
#else
    fprintf(stderr, "[多窗口合成] %s errno=%d(%s)\n", 信息, 错误码, strerror(错误码));
#endif
}

多窗口合成器::多窗口合成器(int 输出宽, int 输出高) {
    if (输出宽 > 0 && 输出宽 <= 8192) 输出宽_ = 输出宽;
    if (输出高 > 0 && 输出高 <= 8192) 输出高_ = 输出高;
    for (int i = 0; i < 最大图层数; ++i) { 槽位占用_[i] = false; 图层表_[i].图层编号 = -1; }
}

多窗口合成器::~多窗口合成器() {}

int 多窗口合成器::设置输出尺寸(int 宽, int 高) {
    if (宽 <= 0 || 高 <= 0 || 宽 > 8192 || 高 > 8192) { 记录日志_合成("输出尺寸越界", ERANGE); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    输出宽_ = 宽; 输出高_ = 高;
    有脏区_ = false; 当前脏区_ = 脏矩形{};
    return 0;
}

int 多窗口合成器::查找槽位_内部(int 图层编号) {
    for (int i = 0; i < 最大图层数; ++i)
        if (槽位占用_[i] && 图层表_[i].图层编号 == 图层编号) return i;
    return -1;
}

int 多窗口合成器::添加图层(const 图层描述& 描述) {
    if (描述.宽 <= 0 || 描述.高 <= 0 || 描述.宽 > 8192 || 描述.高 > 8192) { 记录日志_合成("图层尺寸非法", EINVAL); return -1; }
    if (描述.像素 == nullptr) { 记录日志_合成("图层像素为空", EINVAL); return -2; }
    if (描述.全局透明度 < 0 || 描述.全局透明度 > 255) { 记录日志_合成("透明度越界", ERANGE); return -3; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 空槽 = -1;
    for (int i = 0; i < 最大图层数; ++i) if (!槽位占用_[i]) { 空槽 = i; break; }
    if (空槽 < 0) { 记录日志_合成("图层槽位已满", ENOSPC); return -4; }
    图层描述 拷贝 = 描述;
    拷贝.图层编号 = 下一编号_++;
    if (拷贝.步幅 <= 0) 拷贝.步幅 = 拷贝.宽 * (拷贝.是RGB565 ? 2 : 4);
    图层表_[空槽] = 拷贝; 槽位占用_[空槽] = true;
    有脏区_ = false;
    return 拷贝.图层编号;
}

int 多窗口合成器::更新图层(int 图层编号, const 图层描述& 描述) {
    if (描述.像素 == nullptr) { 记录日志_合成("像素为空", EINVAL); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 槽位 = 查找槽位_内部(图层编号);
    if (槽位 < 0) { 记录日志_合成("图层不存在", ENOENT); return -2; }
    图层描述 拷贝 = 描述; 拷贝.图层编号 = 图层编号;
    if (拷贝.步幅 <= 0) 拷贝.步幅 = 拷贝.宽 * (拷贝.是RGB565 ? 2 : 4);
    图层表_[槽位] = 拷贝;
    return 0;
}

int 多窗口合成器::移除图层(int 图层编号) {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 槽位 = 查找槽位_内部(图层编号);
    if (槽位 < 0) { 记录日志_合成("图层不存在", ENOENT); return -1; }
    槽位占用_[槽位] = false; 图层表_[槽位] = 图层描述{};
    有脏区_ = false;
    return 0;
}

int 多窗口合成器::清空图层() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    for (int i = 0; i < 最大图层数; ++i) { 槽位占用_[i] = false; 图层表_[i] = 图层描述{}; }
    有脏区_ = false;
    return 0;
}

int 多窗口合成器::设置可见性(int 图层编号, bool 可见) {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 槽位 = 查找槽位_内部(图层编号);
    if (槽位 < 0) return -1;
    图层表_[槽位].可见 = 可见;
    return 0;
}

int 多窗口合成器::设置显示顺序(int 图层编号, int 顺序) {
    if (顺序 < -1000 || 顺序 > 1000) return -1;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 槽位 = 查找槽位_内部(图层编号);
    if (槽位 < 0) return -2;
    图层表_[槽位].显示顺序 = 顺序;
    return 0;
}

int 多窗口合成器::设置透明度(int 图层编号, int 透明度) {
    if (透明度 < 0 || 透明度 > 255) return -1;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 槽位 = 查找槽位_内部(图层编号);
    if (槽位 < 0) return -2;
    图层表_[槽位].全局透明度 = 透明度;
    return 0;
}

int 多窗口合成器::移动图层(int 图层编号, int 左, int 上) {
    if (左 < -8192 || 上 < -8192 || 左 > 8192 || 上 > 8192) return -1;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 槽位 = 查找槽位_内部(图层编号);
    if (槽位 < 0) return -2;
    图层表_[槽位].左 = 左; 图层表_[槽位].上 = 上;
    return 0;
}

int 多窗口合成器::获取图层数() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 计数 = 0;
    for (int i = 0; i < 最大图层数; ++i) if (槽位占用_[i]) 计数++;
    return 计数;
}

int 多窗口合成器::排序索引_内部(int* 输出索引, int 输出容量) {
    int 计数 = 0;
    for (int i = 0; i < 最大图层数 && 计数 < 输出容量; ++i)
        if (槽位占用_[i] && 图层表_[i].可见) 输出索引[计数++] = i;
    for (int i = 1; i < 计数; ++i) {
        int 键 = 输出索引[i], j = i - 1;
        while (j >= 0 && 图层表_[输出索引[j]].显示顺序 > 图层表_[键].显示顺序) { 输出索引[j+1] = 输出索引[j]; --j; }
        输出索引[j+1] = 键;
    }
    return 计数;
}

int 多窗口合成器::混合单图层按尺寸_内部(void* 目标, int 目标步幅, const 图层描述& 图层, int 输出宽, int 输出高) {
    if (目标 == nullptr || 图层.像素 == nullptr) return -1;
    if (图层.宽 <= 0 || 图层.高 <= 0 || 输出宽 <= 0 || 输出高 <= 0) return -1;
    if (目标步幅 < 输出宽 * 4) return -1;
    // 裁剪一次性提升：原实现逐像素判断目标行列越界，现行列起止一次算好，内层无越界分支。
    int 行起 = 图层.上 < 0 ? 0 : 图层.上;
    int 行止 = 图层.上 + 图层.高 > 输出高 ? 输出高 : 图层.上 + 图层.高;
    int 列起 = 图层.左 < 0 ? 0 : 图层.左;
    int 列止 = 图层.左 + 图层.宽 > 输出宽 ? 输出宽 : 图层.左 + 图层.宽;
    if (行起 >= 行止 || 列起 >= 列止) return 0;
    int 透明度 = 图层.全局透明度;
    if (透明度 <= 0) return 0;
    if (透明度 > 255) 透明度 = 255;
    uint8_t* 目标行 = (uint8_t*)目标;
    const uint8_t* 源行 = (const uint8_t*)图层.像素;
    int 源列偏 = 列起 - 图层.左;
    int 混合宽 = 列止 - 列起;
    if (图层.是RGB565) {
        // RGB565 分不透明/半透明两条行循环：格式分支在行循环之外，内层无格式判断；
        // 5/6bit 用位复制展开替代除法。
        if (透明度 == 255) {
            for (int 目标Y = 行起; 目标Y < 行止; ++目标Y) {
                const uint16_t* 源16 = (const uint16_t*)(源行 + (size_t)(目标Y - 图层.上) * (size_t)图层.步幅) + 源列偏;
                uint8_t* 目标像素行 = 目标行 + (size_t)目标Y * (size_t)目标步幅 + (size_t)列起 * 4;
                for (int k = 0; k < 混合宽; ++k) {
                    uint16_t 像素 = 源16[k];
                    uint32_t 红5 = (像素 >> 11) & 0x1F, 绿6 = (像素 >> 5) & 0x3F, 蓝5 = 像素 & 0x1F;
                    目标像素行[k*4+0] = (uint8_t)((蓝5 << 3) | (蓝5 >> 2));
                    目标像素行[k*4+1] = (uint8_t)((绿6 << 2) | (绿6 >> 4));
                    目标像素行[k*4+2] = (uint8_t)((红5 << 3) | (红5 >> 2));
                    目标像素行[k*4+3] = 0xFF;
                }
            }
        } else {
            int 逆 = 255 - 透明度;
            for (int 目标Y = 行起; 目标Y < 行止; ++目标Y) {
                const uint16_t* 源16 = (const uint16_t*)(源行 + (size_t)(目标Y - 图层.上) * (size_t)图层.步幅) + 源列偏;
                uint8_t* 目标像素行 = 目标行 + (size_t)目标Y * (size_t)目标步幅 + (size_t)列起 * 4;
                for (int k = 0; k < 混合宽; ++k) {
                    uint16_t 像素 = 源16[k];
                    uint32_t 红 = (((像素 >> 11) & 0x1F) << 3) | (((像素 >> 11) & 0x1F) >> 2);
                    uint32_t 绿 = (((像素 >> 5) & 0x3F) << 2) | (((像素 >> 5) & 0x3F) >> 4);
                    uint32_t 蓝 = ((像素 & 0x1F) << 3) | ((像素 & 0x1F) >> 2);
                    目标像素行[k*4+0] = (uint8_t)((蓝 * (uint32_t)透明度 + 目标像素行[k*4+0] * (uint32_t)逆 + 127) / 255);
                    目标像素行[k*4+1] = (uint8_t)((绿 * (uint32_t)透明度 + 目标像素行[k*4+1] * (uint32_t)逆 + 127) / 255);
                    目标像素行[k*4+2] = (uint8_t)((红 * (uint32_t)透明度 + 目标像素行[k*4+2] * (uint32_t)逆 + 127) / 255);
                    目标像素行[k*4+3] = 0xFF;
                }
            }
        }
    } else {
        for (int 目标Y = 行起; 目标Y < 行止; ++目标Y) {
            const uint8_t* 源像素行 = 源行 + (size_t)(目标Y - 图层.上) * (size_t)图层.步幅 + (size_t)源列偏 * 4;
            uint8_t* 目标像素行 = 目标行 + (size_t)目标Y * (size_t)目标步幅 + (size_t)列起 * 4;
            // 不透明像素整像素拷贝、全透明跳过，仅半透明走混合算术，常见全不透明图层接近 memcpy 速度。
            for (int k = 0; k < 混合宽; ++k) {
                const uint8_t* 像素源 = 源像素行 + (size_t)k * 4;
                uint8_t* 像素目 = 目标像素行 + (size_t)k * 4;
                int 混合透明 = (像素源[3] * 透明度 + 127) / 255;
                if (混合透明 >= 255) {
                    像素目[0] = 像素源[0]; 像素目[1] = 像素源[1]; 像素目[2] = 像素源[2]; 像素目[3] = 0xFF;
                } else if (混合透明 > 0) {
                    int 逆 = 255 - 混合透明;
                    像素目[0] = (uint8_t)((像素源[0] * 混合透明 + 像素目[0] * 逆 + 127) / 255);
                    像素目[1] = (uint8_t)((像素源[1] * 混合透明 + 像素目[1] * 逆 + 127) / 255);
                    像素目[2] = (uint8_t)((像素源[2] * 混合透明 + 像素目[2] * 逆 + 127) / 255);
                    像素目[3] = 0xFF;
                }
            }
        }
    }
    return 0;
}

int 多窗口合成器::混合单图层_内部(void* 目标, int 目标步幅, const 图层描述& 图层) {
    // 兼容入口：调用者已持锁时使用成员尺寸分发，主体逻辑在按尺寸版本中单份实现。
    return 混合单图层按尺寸_内部(目标, 目标步幅, 图层, 输出宽_, 输出高_);
}


int 多窗口合成器::合成到内存(void* 目标, int 目标步幅) {
    if (目标 == nullptr) { 记录日志_合成("目标为空", EINVAL); return -1; }
    // 快照后解锁再合成：原实现全程持锁做背景填充加全部图层混合，大帧会阻塞图层增删与垂直同步。
    // 现锁内只做步幅校验与表拷贝，像素工作全部在锁外。
    int 输出宽快照 = 0, 输出高快照 = 0;
    uint32_t 背景快照 = 0;
    图层描述 图层快照[16];
    bool 占用快照[16] = {};
    {
        std::lock_guard<std::mutex> 守卫(互斥锁_);
        if (目标步幅 < 输出宽_ * 4) { 记录日志_合成("目标步幅不足", EINVAL); return -2; }
        输出宽快照 = 输出宽_; 输出高快照 = 输出高_; 背景快照 = 背景色_;
        for (int i = 0; i < 最大图层数; ++i) { 图层快照[i] = 图层表_[i]; 占用快照[i] = 槽位占用_[i]; }
    }
    if (输出宽快照 <= 0 || 输出高快照 <= 0) { 记录日志_合成("输出尺寸非法", ERANGE); return -2; }
    // 背景填充：32 位整像素行写入替代逐字节四通道循环。
    uint32_t 背景像素 = (背景快照 & 0x00FFFFFFu) | 0xFF000000u;
    uint8_t* 目标行 = (uint8_t*)目标;
    for (int 行 = 0; 行 < 输出高快照; ++行) {
        uint32_t* 像素行 = (uint32_t*)(目标行 + (size_t)行 * (size_t)目标步幅);
        for (int 列 = 0; 列 < 输出宽快照; ++列) 像素行[列] = 背景像素;
    }
    int 索引表[16]; int 计数 = 0;
    for (int i = 0; i < 最大图层数 && 计数 < 16; ++i)
        if (占用快照[i] && 图层快照[i].可见) 索引表[计数++] = i;
    for (int i = 1; i < 计数; ++i) {
        int 键 = 索引表[i], j = i - 1;
        while (j >= 0 && 图层快照[索引表[j]].显示顺序 > 图层快照[键].显示顺序) { 索引表[j+1] = 索引表[j]; --j; }
        索引表[j+1] = 键;
    }
    for (int k = 0; k < 计数; ++k) {
        int 结果 = 混合单图层按尺寸_内部(目标, 目标步幅, 图层快照[索引表[k]], 输出宽快照, 输出高快照);
        if (结果 != 0) { 记录日志_合成("单图层混合失败", EIO); return -3; }
    }
    return 0;
}


int 多窗口合成器::合成并上屏(ANativeWindow* 窗口) {
    if (窗口 == nullptr) { 记录日志_合成("窗口为空", EINVAL); return -1; }
#if defined(__ANDROID__)
    ANativeWindow_Buffer 缓冲{};
    ARect 范围{0, 0, 输出宽_, 输出高_};
    int 锁定结果 = ANativeWindow_lock(窗口, &缓冲, &范围);
    if (锁定结果 != 0) { 记录日志_合成("窗口锁定失败", EIO); return -2; }
    if (缓冲.bits == nullptr) { 记录日志_合成("背缓冲为空", ENODATA); return -3; }
    int 目标步幅 = 缓冲.stride * 4;
    int 合成结果 = 合成到内存(缓冲.bits, 目标步幅);
    ANativeWindow_unlockAndPost(窗口);
    if (合成结果 != 0) { 记录日志_合成("合成失败", EIO); return -4; }
    return 0;
#else
    (void)窗口;
    // 宿主环境：分配临时内存做离屏合成演练，保证逻辑可验证。
    // 加固：合成缓冲上界 64MB，避免超大输出尺寸导致 unbounded 分配拖死宿主。
    if (输出宽_ <= 0 || 输出高_ <= 0 || 输出宽_ > 8192 || 输出高_ > 8192) { 记录日志_合成("输出尺寸非法", ERANGE); return -5; }
    size_t 大小 = (size_t)输出宽_ * (size_t)输出高_ * 4;
    if (大小 == 0 || 大小 > ((size_t)64 << 20)) { 记录日志_合成("合成缓冲越界", ERANGE); return -5; }
    void* 临时 = malloc(大小);
    if (!临时) { 记录日志_合成("内存不足", ENOMEM); return -5; }
    int 结果 = 合成到内存(临时, 输出宽_ * 4);
    free(临时);
    return 结果;
#endif
}

int 多窗口合成器::标记脏区(int 左, int 上, int 右, int 下) {
    if (右 <= 左 || 下 <= 上) { 记录日志_合成("脏区为空", EINVAL); return -1; }
    if (左 < -8192 || 上 < -8192 || 右 > 16384 || 下 > 16384) return -2;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    if (!有脏区_) { 当前脏区_ = 脏矩形{左, 上, 右, 下}; 有脏区_ = true; }
    else {
        if (左 < 当前脏区_.左) 当前脏区_.左 = 左;
        if (上 < 当前脏区_.上) 当前脏区_.上 = 上;
        if (右 > 当前脏区_.右) 当前脏区_.右 = 右;
        if (下 > 当前脏区_.下) 当前脏区_.下 = 下;
    }
    return 0;
}

int 多窗口合成器::清除脏区() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    有脏区_ = false; 当前脏区_ = 脏矩形{};
    return 0;
}

int 多窗口合成器::获取脏区(脏矩形* 输出) {
    if (!输出) return -1;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    if (!有脏区_) return -2;
    *输出 = 当前脏区_;
    return 0;
}

