// 加固：16 个脏区合并策略折叠为单个按扩展像素参数化成员 + 奇偶扩展表（偶数外包、奇数外扩 1 像素）。
int64_t 多窗口合成器::脏区合并按策略_内部(int 左, int 上, int 右, int 下, int 扩展像素) {
    if (右 <= 左 || 下 <= 上) { 记录日志_合成("脏区为空", EINVAL); return -1; }
    if (左 < -8192) 左 = -8192; if (上 < -8192) 上 = -8192;
    if (右 > 16384) 右 = 16384; if (下 > 16384) 下 = 16384;
    if (扩展像素 < 0) 扩展像素 = 0;
    if (扩展像素 > 16) 扩展像素 = 16;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 合并左 = 有脏区_ ? std::min(当前脏区_.左, 左) : 左;
    int 合并上 = 有脏区_ ? std::min(当前脏区_.上, 上) : 上;
    int 合并右 = 有脏区_ ? std::max(当前脏区_.右, 右) : 右;
    int 合并下 = 有脏区_ ? std::max(当前脏区_.下, 下) : 下;
    合并左 -= 扩展像素; 合并上 -= 扩展像素; 合并右 += 扩展像素; 合并下 += 扩展像素;
    当前脏区_ = 脏矩形{合并左, 合并上, 合并右, 合并下};
    有脏区_ = true;
    int64_t 面积 = (int64_t)(合并右 - 合并左) * (合并下 - 合并上);
    if (面积 < 0) { 记录日志_合成("面积溢出", ERANGE); return -2; }
    return 面积;
}
