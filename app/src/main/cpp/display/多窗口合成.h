struct ANativeWindow;
struct ANativeWindow_Buffer;

// 图层描述（中文结构体）：描述一个待合成窗口的位置、尺寸、透明度与像素来源。
struct 图层描述 {
    int 图层编号 = -1;
    int 左 = 0;
    int 上 = 0;
    int 宽 = 0;
    int 高 = 0;
    int 步幅 = 0;
    int 全局透明度 = 255;
    int 显示顺序 = 0;
    bool 可见 = true;
    bool 是RGB565 = false;
    const void* 像素 = nullptr;
};

// 脏矩形（中文结构体）：合成时仅重绘脏区，降低带宽。
struct 脏矩形 {
    int 左 = 0; int 上 = 0; int 右 = 0; int 下 = 0;
    bool 为空() const { return 右 <= 左 || 下 <= 上; }
};

