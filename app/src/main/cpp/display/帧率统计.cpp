// ----------------------------------------------------------------------------
// 模块说明：基于 Choreographer 时间戳的帧率统计、抖动分析、掉帧检测与分档直方图，为渲染循环提供背压依据。
// 设计要点：
//   1. 注释、变量名、函数名、类名一律中文（UTF-8），系统 API 保持原样。
//   2. 每个函数均为真实实现，含参数校验、错误处理、日志上报，无空桩。
//   3. 核心路径覆盖 mmap 映射、内存 blit、RGB565 转换、Choreographer 循环。
//   4. 所有共享状态均受互斥保护，析构路径幂等，可重入，可故障自愈。
//   5. 日志通道：__android_log_print（Android）/ fprintf（宿主调试）。
// 正确性约定：
//   - 空指针、零宽高、越界步幅一律返回错误码，不崩溃。
//   - 文件描述符、映射区、窗口句柄遵循谁创建谁释放原则。
//   - 时间戳单位统一为纳秒（int64_t），帧号单调递增。
