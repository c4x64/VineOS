int 帧率统计器::保存快照(const char* 文件路径) {
    if (文件路径 == nullptr || 文件路径[0] == '\0') {
        记录日志_帧率("错误", "文件路径为空", EINVAL); return -1;
    }
    // 锁内只做内存拷贝，阻塞写移到锁外：原实现持锁做三次 write，文件系统抖动会阻塞垂直同步记录。
    int64_t 环形拷贝[512]; int64_t 直方图拷贝[16]; int64_t 总数拷贝 = 0;
    {
        std::lock_guard<std::mutex> 守卫(互斥锁_);
        memcpy(环形拷贝, 环形时间_, sizeof(环形拷贝));
        memcpy(直方图拷贝, 直方图_, sizeof(直方图拷贝));
        总数拷贝 = 总帧数_;
    }
    int 描述符 = open(文件路径, O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, 0644);
    if (描述符 < 0) { 记录日志_帧率("错误", "打开快照失败", errno); return -2; }
    const void* 数据段[3] = {环形拷贝, 直方图拷贝, &总数拷贝};
    const size_t 长度段[3] = {sizeof(环形拷贝), sizeof(直方图拷贝), sizeof(总数拷贝)};
    for (int 段 = 0; 段 < 3; ++段) {
        size_t 已写 = 0;
        while (已写 < 长度段[段]) {
            ssize_t 单次 = write(描述符, (const uint8_t*)数据段[段] + 已写, 长度段[段] - 已写);
            if (单次 < 0) {
                if (errno == EINTR) continue;
                int 保存错误 = errno;
                close(描述符);
                记录日志_帧率("错误", "写入快照不完整", 保存错误);
                return -3;
            }
            if (单次 == 0) { close(描述符); 记录日志_帧率("错误", "写入快照不完整", EIO); return -3; }
            已写 += (size_t)单次;
        }
    }
    close(描述符);
    return 0;
}


int 帧率统计器::恢复快照(const char* 文件路径) {
    if (文件路径 == nullptr || 文件路径[0] == '\0') {
        记录日志_帧率("错误", "文件路径为空", EINVAL); return -1;
    }
    // 阻塞读在锁外完成，读完校验通过后再持锁提交，避免磁盘等待阻塞记录路径。
    int 描述符 = open(文件路径, O_RDONLY | O_CLOEXEC);
    if (描述符 < 0) { 记录日志_帧率("错误", "打开快照失败", errno); return -2; }
    int64_t 临时环形[512]; int64_t 临时直方[16]; int64_t 临时总数 = 0;
    void* 数据段[3] = {临时环形, 临时直方, &临时总数};
    const size_t 长度段[3] = {sizeof(临时环形), sizeof(临时直方), sizeof(临时总数)};
    for (int 段 = 0; 段 < 3; ++段) {
        size_t 已读 = 0;
        while (已读 < 长度段[段]) {
            ssize_t 单次 = read(描述符, (uint8_t*)数据段[段] + 已读, 长度段[段] - 已读);
            if (单次 < 0) {
                if (errno == EINTR) continue;
                int 恢复错误 = errno;
                close(描述符);
                记录日志_帧率("错误", "读取快照不完整", 恢复错误);
                return -3;
            }
            if (单次 == 0) { close(描述符); 记录日志_帧率("错误", "读取快照不完整", ENODATA); return -3; }
            已读 += (size_t)单次;
        }
    }
    close(描述符);
    if (临时总数 < 0) { 记录日志_帧率("错误", "快照总数非法", EINVAL); return -4; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    memcpy(环形时间_, 临时环形, sizeof(环形时间_));
    memcpy(直方图_, 临时直方, sizeof(直方图_));
    总帧数_ = 临时总数;
    环形头_ = 0; 环形计数_ = 环形容量 > 512 ? 512 : 环形容量;
    int64_t 最大值 = 0;
    for (int i = 0; i < 环形容量; ++i) if (环形时间_[i] > 最大值) 最大值 = 环形时间_[i];
    上一帧时间_ = 最大值;
    return 0;
}


void 帧率统计器::垂直同步回调(long 帧时间纳秒, void* 上下文) {
    if (上下文 == nullptr) return;
    auto* 统计器 = static_cast<帧率统计器*>(上下文);
    // Choreographer 给的是 long（32 位平台截断风险），先做合法性钳制再记录。
    if (帧时间纳秒 <= 0) return;
    统计器->记录帧到达((int64_t)帧时间纳秒);
    // 注意：重挂逻辑由拥有 AChoreographer 句柄的渲染循环负责，此处仅统计，避免重复挂载。
}

// 加固：32 个分档统计函数体折叠为边界查找表 + 单个参数化成员，包装函数仅做表索引转发。
// 原实现每函数重复一次全量环形扫描与边界计算；现边界来自静态表，扫描逻辑单份，指令缓存友好。
// 如需一次查询全部分档，建议调用获取直方图（单次拷贝）而非轮询 32 个包装函数（32 次扫描）。
static const int64_t 分档下界表_帧率[32] = {
    0LL, 2000000LL, 4000000LL, 6000000LL, 8000000LL, 10000000LL, 12000000LL, 14000000LL,
    16000000LL, 18000000LL, 20000000LL, 22000000LL, 24000000LL, 26000000LL, 28000000LL, 30000000LL,
    32000000LL, 34000000LL, 36000000LL, 38000000LL, 40000000LL, 42000000LL, 44000000LL, 46000000LL,
    48000000LL, 50000000LL, 52000000LL, 54000000LL, 56000000LL, 58000000LL, 60000000LL, 62000000LL};
static const int64_t 分档上界表_帧率[32] = {
    2000000LL, 4000000LL, 6000000LL, 8000000LL, 10000000LL, 12000000LL, 14000000LL, 16000000LL,
    18000000LL, 20000000LL, 22000000LL, 24000000LL, 26000000LL, 28000000LL, 30000000LL, 32000000LL,
    34000000LL, 36000000LL, 38000000LL, 40000000LL, 42000000LL, 44000000LL, 46000000LL, 48000000LL,
    50000000LL, 52000000LL, 54000000LL, 56000000LL, 58000000LL, 60000000LL, 62000000LL, 64000000LL};
int 帧率统计器::分档统计按档号_内部(int 档号) {
    if (档号 < 0 || 档号 >= 32) { 记录日志_帧率("错误", "分档档号越界", ERANGE); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 有效数 = 有效样本数_内部();
    if (有效数 < 2) return 0;
    int64_t 下界纳秒 = 分档下界表_帧率[档号];
    int64_t 上界纳秒 = 分档上界表_帧率[档号];
    bool 是末档 = (档号 == 31);
    int 最旧下标 = (环形头_ - 有效数 + 环形容量 * 2) % 环形容量;
    int64_t 前一时间 = 环形时间_[最旧下标];
    int 下标 = 最旧下标;
    int 命中 = 0;
    for (int 步 = 1; 步 < 有效数; ++步) {
        下标++;
        if (下标 >= 环形容量) 下标 -= 环形容量;
        int64_t 当前 = 环形时间_[下标];
        if (当前 <= 0 || 前一时间 <= 0 || 当前 < 前一时间) { 前一时间 = 当前; continue; }
        int64_t 间隔 = 当前 - 前一时间;
        前一时间 = 当前;
        if (间隔 > 1000000000LL) 间隔 = 1000000000LL;
        if (是末档 ? (间隔 >= 下界纳秒) : (间隔 >= 下界纳秒 && 间隔 < 上界纳秒)) 命中++;
    }
    return 命中;
}
