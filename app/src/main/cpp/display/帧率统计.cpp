// 内部日志：Android 走 __android_log_print，宿主走 fprintf，保证两端可见。
static void 记录日志_帧率(const char* 级别, const char* 信息, int 错误码) {
#if defined(__ANDROID__)
    __android_log_print(6, "帧率统计", "[%s] %s errno=%d(%s)", 级别, 信息, 错误码, strerror(错误码));
#else
    fprintf(stderr, "[帧率统计][%s] %s errno=%d(%s)\n", 级别, 信息, 错误码, strerror(错误码));
#endif
}

// 构造：校验窗口长度与周期合法性，非法则取默认值并记日志。
帧率统计器::帧率统计器(int 窗口长度, int64_t 期望周期纳秒) {
    if (窗口长度 <= 0 || 窗口长度 > 环形容量) {
        记录日志_帧率("警告", "窗口长度非法，已修正为 120", EINVAL);
        窗口长度 = 120;
    }
    if (期望周期纳秒 <= 0 || 期望周期纳秒 > 1000000000LL) {
        记录日志_帧率("警告", "期望周期非法，已修正为 16666666", EINVAL);
        期望周期纳秒 = 16666666LL;
    }
    窗口长度_ = 窗口长度;
    期望周期纳秒_ = 期望周期纳秒;
    for (int 索引 = 0; 索引 < 环形容量; ++索引) 环形时间_[索引] = 0;
    for (int 索引 = 0; 索引 < 直方图档数; ++索引) 直方图_[索引] = 0;
    已初始化_ = true;
}

帧率统计器::~帧率统计器() {
    已初始化_ = false;
}

int 帧率统计器::有效样本数_内部() const {
    int 可用 = 环形计数_ < 窗口长度_ ? 环形计数_ : 窗口长度_;
    if (可用 < 0) 可用 = 0;
    if (可用 > 环形容量) 可用 = 环形容量;
    return 可用;
}

int64_t 帧率统计器::帧间隔_内部(int 环形下标) const {
    if (环形下标 < 0 || 环形下标 >= 环形容量) return -1;
    int 前一下标 = (环形下标 - 1 + 环形容量) % 环形容量;
    int64_t 当前 = 环形时间_[环形下标];
    int64_t 之前 = 环形时间_[前一下标];
    if (当前 <= 0 || 之前 <= 0) return -1;
    int64_t 差值 = 当前 - 之前;
    if (差值 < 0) return -1;
    if (差值 > 1000000000LL) 差值 = 1000000000LL;
    return 差值;
}

void 帧率统计器::更新直方图与掉帧_内部(int64_t 间隔纳秒) {
    if (间隔纳秒 < 0) return;
    int64_t 档宽 = 期望周期纳秒_ / 2;
    if (档宽 <= 0) 档宽 = 8333333LL;
    int 档位 = (int)(间隔纳秒 / 档宽);
    if (档位 < 0) 档位 = 0;
    if (档位 >= 直方图档数) 档位 = 直方图档数 - 1;
    直方图_[档位]++;
    int64_t 掉帧阈值 = (期望周期纳秒_ * 3) / 2;
    if (间隔纳秒 > 掉帧阈值) {
        连续掉帧_++;
    } else {
        连续掉帧_ = 0;
    }
}

int 帧率统计器::记录帧到达(int64_t 帧时间纳秒) {
    if (帧时间纳秒 <= 0) { 记录日志_帧率("错误", "帧时间非法", EINVAL); return -1; }
    if (!已初始化_) { 记录日志_帧率("错误", "统计器未初始化", ENODEV); return -2; }
    // 单次加锁：原 try_lock 后转阻塞锁为空转等待，加固后直接阻塞锁，消除自旋与双重加锁开销。
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    if (上一帧时间_ > 0) {
        if (帧时间纳秒 > 上一帧时间_) {
            int64_t 间隔 = 帧时间纳秒 - 上一帧时间_;
            if (间隔 > 1000000000LL) 间隔 = 1000000000LL;
            更新直方图与掉帧_内部(间隔);
        } else {
            记录日志_帧率("警告", "帧时间非单调，已按当前值覆盖", EINVAL);
        }
    }
    环形时间_[环形头_] = 帧时间纳秒;
    环形头_ = (环形头_ + 1) % 环形容量;
    if (环形计数_ < 环形容量) 环形计数_++;
    上一帧时间_ = 帧时间纳秒;
    总帧数_++;
    return 0;
}


int 帧率统计器::批量记录(const int64_t* 时间数组, int 个数) {
    if (时间数组 == nullptr) { 记录日志_帧率("错误", "时间数组为空", EINVAL); return -1; }
    if (个数 <= 0 || 个数 > 100000) { 记录日志_帧率("错误", "个数越界", ERANGE); return -1; }
    if (!已初始化_) { 记录日志_帧率("错误", "统计器未初始化", ENODEV); return -2; }
    // 单次加锁批量写入：原实现逐帧调用记录帧到达（每帧一次加锁），回放 10 万帧即 10 万次加锁。
    // 加固后一次加锁整体写入，直方图更新内联，非法时间戳计数后统一记一条日志，避免日志刷屏。
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int64_t 档宽 = 期望周期纳秒_ / 2;
    if (档宽 <= 0) 档宽 = 8333333LL;
    int64_t 掉帧阈值 = (期望周期纳秒_ * 3) / 2;
    int 成功数 = 0, 跳过数 = 0;
    int64_t 上一帧 = 上一帧时间_;
    for (int 索引 = 0; 索引 < 个数; ++索引) {
        int64_t 时间戳 = 时间数组[索引];
        if (时间戳 <= 0) { 跳过数++; continue; }
        if (上一帧 > 0 && 时间戳 > 上一帧) {
            int64_t 间隔 = 时间戳 - 上一帧;
            if (间隔 > 1000000000LL) 间隔 = 1000000000LL;
            int 档位 = (int)(间隔 / 档宽);
            if (档位 < 0) 档位 = 0;
            if (档位 >= 直方图档数) 档位 = 直方图档数 - 1;
            直方图_[档位]++;
            if (间隔 > 掉帧阈值) 连续掉帧_++; else 连续掉帧_ = 0;
        }
        环形时间_[环形头_] = 时间戳;
        环形头_ = (环形头_ + 1) % 环形容量;
        if (环形计数_ < 环形容量) 环形计数_++;
        上一帧 = 时间戳;
        成功数++;
    }
    上一帧时间_ = 上一帧;
    总帧数_ += 成功数;
    if (跳过数 > 0) 记录日志_帧率("警告", "批量记录跳过非法时间戳", EINVAL);
    return 成功数;
}


int 帧率统计器::重置统计() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    for (int 索引 = 0; 索引 < 环形容量; ++索引) 环形时间_[索引] = 0;
    for (int 索引 = 0; 索引 < 直方图档数; ++索引) 直方图_[索引] = 0;
    环形头_ = 0; 环形计数_ = 0; 总帧数_ = 0;
    连续掉帧_ = 0; 上一帧时间_ = 0;
    return 0;
}

double 帧率统计器::计算实时帧率() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    if (环形计数_ < 2) return -1.0;
    int 最新下标 = (环形头_ - 1 + 环形容量) % 环形容量;
    int 次新下标 = (环形头_ - 2 + 环形容量) % 环形容量;
    int64_t 间隔 = 环形时间_[最新下标] - 环形时间_[次新下标];
    if (间隔 <= 0) return -1.0;
    if (间隔 > 1000000000LL) return 0.0;
    return 1000000000.0 / (double)间隔;
}

double 帧率统计器::计算平均帧率() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 有效数 = 有效样本数_内部();
    if (有效数 < 2) return -1.0;
    int 最新下标 = (环形头_ - 1 + 环形容量) % 环形容量;
    int 最旧下标 = (环形头_ - 有效数 + 环形容量 * 2) % 环形容量;
    int64_t 跨度 = 环形时间_[最新下标] - 环形时间_[最旧下标];
    if (跨度 <= 0) return -1.0;
    return (double)(有效数 - 1) * 1000000000.0 / (double)跨度;
}

int 帧率统计器::计算间隔极值(int64_t* 最小值, int64_t* 最大值, int64_t* 平均值) {
    if (最小值 == nullptr || 最大值 == nullptr || 平均值 == nullptr) {
        记录日志_帧率("错误", "输出指针为空", EINVAL); return -1;
    }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 有效数 = 有效样本数_内部();
    if (有效数 < 2) { 记录日志_帧率("警告", "样本不足", ENODATA); return -2; }
    int64_t 最小 = INT64_MAX, 最大 = 0, 累加 = 0;
    int 计数 = 0;
    for (int 偏移 = 1; 偏移 < 有效数; ++偏移) {
        int 下标 = (环形头_ - 偏移 + 环形容量 * 2) % 环形容量;
        int64_t 间隔 = 帧间隔_内部(下标);
        if (间隔 < 0) continue;
        if (间隔 < 最小) 最小 = 间隔;
        if (间隔 > 最大) 最大 = 间隔;
        累加 += 间隔; 计数++;
    }
    if (计数 == 0) return -2;
    *最小值 = 最小; *最大值 = 最大; *平均值 = 累加 / 计数;
    return 0;
}

double 帧率统计器::计算抖动标准差() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 有效数 = 有效样本数_内部();
    if (有效数 < 3) return -1.0;
    // 单遍 Welford 在线算法：原实现两次全量扫描（均值一遍、方差一遍），现均值方差一遍求出。
    // 顺序游走替代逐元素取模：先定位最旧下标再顺序递增。
    int 最旧下标 = (环形头_ - 有效数 + 环形容量 * 2) % 环形容量;
    int64_t 前一时间 = 环形时间_[最旧下标];
    int 下标 = 最旧下标;
    double 均值 = 0.0, 累积方差 = 0.0;
    int 计数 = 0;
    for (int 步 = 1; 步 < 有效数; ++步) {
        下标++;
        if (下标 >= 环形容量) 下标 -= 环形容量;
        int64_t 当前 = 环形时间_[下标];
        if (当前 <= 0 || 前一时间 <= 0 || 当前 < 前一时间) { 前一时间 = 当前; continue; }
        int64_t 间隔 = 当前 - 前一时间;
        if (间隔 > 1000000000LL) 间隔 = 1000000000LL;
        前一时间 = 当前;
        计数++;
        double 差 = (double)间隔 - 均值;
        均值 += 差 / (double)计数;
        累积方差 += 差 * ((double)间隔 - 均值);
    }
    if (计数 < 2) return -1.0;
    return sqrt(累积方差 / (double)计数);
}


int64_t 帧率统计器::计算百分位耗时(int 百分位) {
    if (百分位 != 50 && 百分位 != 90 && 百分位 != 95 && 百分位 != 99) {
        记录日志_帧率("错误", "百分位仅支持 50/90/95/99", EINVAL); return -1;
    }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 有效数 = 有效样本数_内部();
    if (有效数 < 2) return -1;
    int64_t 暂存[512]; int 计数 = 0;
    int 最旧下标 = (环形头_ - 有效数 + 环形容量 * 2) % 环形容量;
    int64_t 前一时间 = 环形时间_[最旧下标];
    int 下标 = 最旧下标;
    for (int 步 = 1; 步 < 有效数 && 计数 < 环形容量; ++步) {
        下标++;
        if (下标 >= 环形容量) 下标 -= 环形容量;
        int64_t 当前 = 环形时间_[下标];
        if (当前 <= 0 || 前一时间 <= 0 || 当前 < 前一时间) { 前一时间 = 当前; continue; }
        int64_t 间隔 = 当前 - 前一时间;
        if (间隔 > 1000000000LL) 间隔 = 1000000000LL;
        前一时间 = 当前;
        暂存[计数++] = 间隔;
    }
    if (计数 == 0) return -1;
    // 线性选择替代插入排序：百分位只需第 k 小元素，nth_element 均摊线性，原插入排序最坏平方。
    int 位置 = (百分位 * 计数 + 99) / 100 - 1;
    if (位置 < 0) 位置 = 0;
    if (位置 >= 计数) 位置 = 计数 - 1;
    std::nth_element(暂存, 暂存 + 位置, 暂存 + 计数);
    return 暂存[位置];
}


int 帧率统计器::统计掉帧数() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int64_t 阈值 = (期望周期纳秒_ * 3) / 2;
    int 掉帧 = 0;
    int 有效数 = 有效样本数_内部();
    for (int 偏移 = 1; 偏移 < 有效数; ++偏移) {
        int 下标 = (环形头_ - 偏移 + 环形容量 * 2) % 环形容量;
        int64_t 间隔 = 帧间隔_内部(下标);
        if (间隔 > 阈值) 掉帧++;
    }
    return 掉帧;
}

int 帧率统计器::统计严重掉帧数() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int64_t 阈值 = (期望周期纳秒_ * 5) / 2;
    int 掉帧 = 0;
    int 有效数 = 有效样本数_内部();
    for (int 偏移 = 1; 偏移 < 有效数; ++偏移) {
        int 下标 = (环形头_ - 偏移 + 环形容量 * 2) % 环形容量;
        int64_t 间隔 = 帧间隔_内部(下标);
        if (间隔 > 阈值) 掉帧++;
    }
    return 掉帧;
}

int64_t 帧率统计器::获取总帧数() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    return 总帧数_;
}

int 帧率统计器::获取直方图(int64_t* 输出数组, int 输出长度) {
    if (输出数组 == nullptr) { 记录日志_帧率("错误", "输出数组为空", EINVAL); return -1; }
    if (输出长度 < 直方图档数) { 记录日志_帧率("错误", "输出长度不足 16", ERANGE); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    for (int 索引 = 0; 索引 < 直方图档数; ++索引) 输出数组[索引] = 直方图_[索引];
    return 0;
}

int 帧率统计器::导出摘要(char* 输出缓冲, int 缓冲长度) {
    if (输出缓冲 == nullptr || 缓冲长度 <= 64) {
        记录日志_帧率("错误", "缓冲非法", EINVAL); return -1;
    }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    int 有效数 = 环形计数_ < 窗口长度_ ? 环形计数_ : 窗口长度_;
    double 平均帧率快照 = -1.0;
    if (有效数 >= 2) {
        int 最新 = (环形头_ - 1 + 环形容量) % 环形容量;
        int 最旧 = (环形头_ - 有效数 + 环形容量 * 2) % 环形容量;
        int64_t 跨度 = 环形时间_[最新] - 环形时间_[最旧];
        if (跨度 > 0) 平均帧率快照 = (double)(有效数 - 1) * 1000000000.0 / (double)跨度;
    }
    int 已写 = snprintf(输出缓冲, (size_t)缓冲长度,
        "总帧数=%lld 有效样本=%d 平均帧率=%.2f 期望周期=%lld 连续掉帧=%d 直方图[0]=%lld [1]=%lld [2]=%lld",
        (long long)总帧数_, 有效数, 平均帧率快照, (long long)期望周期纳秒_,
        连续掉帧_, (long long)直方图_[0], (long long)直方图_[1], (long long)直方图_[2]);
    if (已写 < 0) { 记录日志_帧率("错误", "格式化失败", errno); return -3; }
    if (已写 >= 缓冲长度) { 输出缓冲[缓冲长度-1] = '\0'; return 缓冲长度 - 1; }
    return 已写;
}

