static void 记录日志_自愈(const char* 信息, int 错误码) {
#if defined(__ANDROID__)
    (void)信息; (void)错误码;
#else
    fprintf(stderr, "[故障自愈] %s errno=%d(%s)\n", 信息, 错误码, strerror(错误码));
#endif
}

故障自愈器::故障自愈器(std::string 实例编号) : 实例编号_(std::move(实例编号)) {}
故障自愈器::~故障自愈器() {}

int64_t 故障自愈器::单调毫秒_内部() {
    struct timespec 时间{};
    if (clock_gettime(CLOCK_MONOTONIC, &时间) != 0) return -1;
    return (int64_t)时间.tv_sec * 1000 + 时间.tv_nsec / 1000000;
}

int 故障自愈器::注册映射区(void** 映射指针, size_t* 映射长度) {
    if (!映射指针 || !映射长度) { 记录日志_自愈("映射指针为空", EINVAL); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    映射指针_ = 映射指针; 映射长度_ = 映射长度;
    return 0;
}

int 故障自愈器::注册帧缓冲路径(const char* 设备路径) {
    if (!设备路径 || !设备路径[0]) { 记录日志_自愈("路径为空", EINVAL); return -1; }
    if (strlen(设备路径) > 1024) { 记录日志_自愈("路径过长", ENAMETOOLONG); return -2; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    设备路径_ = 设备路径;
    return 0;
}

int 故障自愈器::上报帧心跳(int64_t 帧时间纳秒) {
    if (帧时间纳秒 <= 0) { 记录日志_自愈("心跳非法", EINVAL); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    最后心跳_ = 单调毫秒_内部();
    if (连续失败_ > 0) 连续失败_--;
    退避毫秒_ = 50;
    return 0;
}

故障码 故障自愈器::巡检一次() {
    // 短锁快照、锁外判定：原实现全程持锁做 msync 探测与时钟调用，阻塞心跳上报与恢复提交。
    // 现锁内只拷贝指针与计数，探测与判定全部在锁外，状态提交时再短锁写入。
    void* 映射快照 = nullptr;
    size_t 长度快照 = 0;
    bool 有映射注册 = false;
    int64_t 心跳快照 = 0;
    int 超时快照 = 0, 失败快照 = 0;
    bool 重建标记 = false;
    {
        std::lock_guard<std::mutex> 守卫(互斥锁_);
        有映射注册 = (映射指针_ != nullptr && 映射长度_ != nullptr);
        if (有映射注册) { 映射快照 = *映射指针_; 长度快照 = *映射长度_; }
        心跳快照 = 最后心跳_; 超时快照 = 超时毫秒_; 失败快照 = 连续失败_; 重建标记 = 需重建窗口_;
    }
    int64_t 现在 = 单调毫秒_内部();
    if (现在 < 0) {
        std::lock_guard<std::mutex> 守卫(互斥锁_);
        连续失败_++;
        return 故障码::线程卡死;
    }
    if (有映射注册) {
        if (映射快照 == nullptr || 映射快照 == MAP_FAILED || 长度快照 == 0) {
            std::lock_guard<std::mutex> 守卫(互斥锁_);
            连续失败_++; 退避毫秒_ = 退避毫秒_ * 2 > 1000 ? 1000 : 退避毫秒_ * 2;
            return 故障码::映射失效;
        }
        if (msync(映射快照, 长度快照 > 4096 ? 4096 : 长度快照, MS_ASYNC) != 0 && errno == ENOMEM) {
            std::lock_guard<std::mutex> 守卫(互斥锁_);
            连续失败_++;
            return 故障码::映射失效;
        }
    }
    if (心跳快照 > 0 && 现在 - 心跳快照 > 超时快照) {
        std::lock_guard<std::mutex> 守卫(互斥锁_);
        连续失败_++;
        if (连续失败_ >= 3) return 故障码::线程卡死;
        return 故障码::超时掉帧;
    }
    if (重建标记) return 故障码::窗口失效;
    if (失败快照 >= 10) return 故障码::描述符泄漏;
    return 故障码::无故障;
}


int 故障自愈器::尝试恢复(故障码 故障) {
    switch (故障) {
        case 故障码::无故障: return 0;
        case 故障码::映射失效: return 重映射帧缓冲();
        case 故障码::窗口失效: return 标记窗口需重建();
        case 故障码::线程卡死: {
            std::lock_guard<std::mutex> 守卫(互斥锁_);
            连续失败_ = 0; 最后心跳_ = 单调毫秒_内部();
            return 0;
        }
        case 故障码::超时掉帧: {
            std::lock_guard<std::mutex> 守卫(互斥锁_);
            if (连续失败_ > 0) 连续失败_--;
            return 0;
        }
        case 故障码::描述符泄漏: case 故障码::几何异常: case 故障码::内存不足: {
            std::lock_guard<std::mutex> 守卫(互斥锁_);
            需重建窗口_ = true;
            return 0;
        }
        default: 记录日志_自愈("未知故障码", EINVAL); return -1;
    }
}

int 故障自愈器::重映射帧缓冲() {
    std::string 路径;
    void** 映射指针 = nullptr; size_t* 映射长度 = nullptr;
    { std::lock_guard<std::mutex> 守卫(互斥锁_); 路径 = 设备路径_; 映射指针 = 映射指针_; 映射长度 = 映射长度_; }
    if (!映射指针 || !映射长度) { 记录日志_自愈("未注册映射", ENODEV); return -1; }
    if (路径.empty()) { 记录日志_自愈("未注册路径", ENODEV); return -2; }
    // 先释放旧映射（幂等：空/MAP_FAILED 均可安全处理）。
    void* 旧映射 = *映射指针; size_t 旧长度 = *映射长度;
    if (旧映射 && 旧映射 != MAP_FAILED && 旧长度 > 0 && 旧长度 <= ((size_t)256 << 20)) munmap(旧映射, 旧长度);
    int 描述符 = open(路径.c_str(), O_RDONLY | O_CLOEXEC);
    if (描述符 < 0) { 记录日志_自愈("打开帧缓冲失败", errno); return -3; }
    off_t 文件大小 = lseek(描述符, 0, SEEK_END);
    if (文件大小 <= 0) {
        // 帧缓冲设备不支持 SEEK_END，回退到 1080x1920x4。
        文件大小 = 1080 * 1920 * 4;
    }
    // 有界映射：钳制在 4KB~64MB 之间，异常设备尺寸直接拒绝，避免超大 mmap 拖死进程。
    if (文件大小 < 4096) 文件大小 = 1080 * 1920 * 4;
    if (文件大小 > (off_t)((size_t)64 << 20)) { close(描述符); 记录日志_自愈("帧缓冲尺寸越界", ERANGE); return -6; }
    lseek(描述符, 0, SEEK_SET);
    void* 新映射 = mmap(nullptr, (size_t)文件大小, PROT_READ, MAP_SHARED, 描述符, 0);
    int 映射错误 = errno;
    close(描述符);
    if (新映射 == MAP_FAILED) { 记录日志_自愈("重映射失败", 映射错误); return -4; }
    { std::lock_guard<std::mutex> 守卫(互斥锁_); *映射指针 = 新映射; *映射长度 = (size_t)文件大小; 连续失败_ = 0; }
    return 0;
}

int 故障自愈器::标记窗口需重建() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    需重建窗口_ = true;
    return 0;
}

bool 故障自愈器::是否需重建窗口() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    return 需重建窗口_;
}

int 故障自愈器::清除重建标记() {
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    需重建窗口_ = false; 连续失败_ = 0;
    return 0;
}

int 故障自愈器::获取健康快照(健康快照* 输出) {
    if (!输出) return -1;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    输出->映射有效 = !(映射指针_ && (*映射指针_ == nullptr || *映射指针_ == MAP_FAILED));
    输出->窗口有效 = !需重建窗口_;
    输出->线程存活 = !(最后心跳_ > 0 && 单调毫秒_内部() - 最后心跳_ > 超时毫秒_);
    输出->最后帧时间 = 最后心跳_;
    输出->连续失败 = 连续失败_;
    输出->主故障 = 连续失败_ == 0 ? 故障码::无故障 : 故障码::超时掉帧;
    return 0;
}

int 故障自愈器::设置超时阈值(int 超时毫秒) {
    if (超时毫秒 < 50 || 超时毫秒 > 10000) { 记录日志_自愈("超时越界", ERANGE); return -1; }
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    超时毫秒_ = 超时毫秒;
    return 0;
}

