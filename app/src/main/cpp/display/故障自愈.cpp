故障码 故障自愈器::按基线诊断_内部(int 基线, int 系统错误码) {
    if (系统错误码 < 0) { 记录日志_自愈("错误码为负", EINVAL); return 故障码::无故障; }
    int 差值 = 系统错误码 > 基线 ? 系统错误码 - 基线 : 基线 - 系统错误码;
    std::lock_guard<std::mutex> 守卫(互斥锁_);
    if (差值 == 0) { 连续失败_++; return 故障码::映射失效; }
    if (系统错误码 == ENOMEM) { 连续失败_++; return 故障码::内存不足; }
    if (系统错误码 == EIO || 系统错误码 == ENODEV) { 连续失败_++; return 故障码::窗口失效; }
    if (差值 < 100) { 连续失败_++; return 故障码::超时掉帧; }
    if (差值 < 500) { 连续失败_++; return 故障码::几何异常; }
    if (差值 < 1000) { 连续失败_++; return 故障码::描述符泄漏; }
    return 故障码::无故障;
}
