// 加固：20 个恢复策略折叠为等待参数表 + 单个参数化成员，退避等待在重映射之前，锁只在状态提交时持有。
static const int 恢复等待表_自愈[20] = {0,20,40,60,80,0,20,40,60,80,0,20,40,60,80,0,20,40,60,80};
int 故障自愈器::按等待恢复_内部(int 等待毫秒) {
    if (等待毫秒 < 0) 等待毫秒 = 0;
    if (等待毫秒 > 500) 等待毫秒 = 500;
    for (int 轮次 = 0; 轮次 < 3; ++轮次) {
        if (等待毫秒 > 0) {
            struct timespec 等待时间{0, (long)等待毫秒 * 1000000L};
            nanosleep(&等待时间, nullptr);
        }
        int 结果 = 重映射帧缓冲();
        if (结果 == 0) {
            std::lock_guard<std::mutex> 守卫(互斥锁_);
            连续失败_ = 0; 退避毫秒_ = 50;
            return 0;
        }
        if (轮次 == 2) { 记录日志_自愈("恢复策略耗尽", EIO); return -1; }
    }
    return -2;
}
