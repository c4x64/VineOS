// ============================================================================
// 帧率统计模块（帧率统计器）
// ----------------------------------------------------------------------------
// 模块说明：基于 Choreographer 时间戳的帧率统计、抖动分析、掉帧检测与分档直方图，为渲染循环提供背压依据。
// 设计要点：
//   1. 注释、变量名、函数名、类名一律中文（UTF-8），系统 API 保持原样。
//   2. 每个函数均为真实实现，含参数校验、错误处理、日志上报，无空桩。
//   3. 核心路径覆盖 mmap 映射、内存 blit、RGB565 转换、Choreographer 循环。
//   4. 所有共享状态均受互斥保护，析构路径幂等，可重入，可故障自愈。
//   5. 日志通道：__android_log_print（Android）/ fprintf（宿主调试）。
// 正确性约定：
//   - 空指针、零宽高、越界步幅一律返回错误码，不崩溃。
//   - 文件描述符、映射区、窗口句柄遵循谁创建谁释放原则。
//   - 时间戳单位统一为纳秒（int64_t），帧号单调递增。
// ============================================================================

#pragma once
#include <cstdint>
#include <cstddef>
#include <string>
#include <vector>
#include <mutex>
#include <atomic>

// 前置声明：垂直同步回调签名与系统一致，时间戳为纳秒。
// 类名：帧率统计器；职责：记录每一帧到达时间，计算实时帧率、平均帧率、
// 百分位耗时、抖动方差，并按帧间隔分档输出直方图，支撑掉帧告警与自适应降载。
class 帧率统计器 {
public:
    // 构造参数：窗口长度（用于滑动平均的帧数，默认 120）、期望垂直同步周期纳秒（默认 16666666）。
    explicit 帧率统计器(int 窗口长度 = 120, int64_t 期望周期纳秒 = 16666666LL);
    ~帧率统计器();
    帧率统计器(const 帧率统计器&) = delete;
    帧率统计器& operator=(const 帧率统计器&) = delete;

    // 记录一帧到达，参数为 Choreographer 回调给出的帧时间（纳秒）。
    // 返回值：0 成功；-1 参数非法；-2 内部锁异常。
    int 记录帧到达(int64_t 帧时间纳秒);
    // 批量记录：用于回放或测试，一次喂入多个时间戳。
    int 批量记录(const int64_t* 时间数组, int 个数);
    // 重置所有统计状态（环形缓冲、计数器、直方图清零）。
    int 重置统计();
    // 计算实时帧率（基于最近两帧间隔），失败返回 -1.0。
    double 计算实时帧率();
    // 计算滑动窗口平均帧率。
    double 计算平均帧率();
    // 计算滑动窗口内帧间隔的最小/最大/平均值（纳秒），结果写入输出指针。
    int 计算间隔极值(int64_t* 最小值, int64_t* 最大值, int64_t* 平均值);
    // 计算抖动标准差（纳秒），用于评估垂直同步稳定性。
    double 计算抖动标准差();
    // 计算百分位耗时（百分位取值 50/90/95/99），返回对应纳秒值，非法返回 -1。
    int64_t 计算百分位耗时(int 百分位);
    // 统计掉帧数（间隔超过 1.5 倍期望周期的帧数）。
    int 统计掉帧数();
    // 统计严重掉帧数（间隔超过 2.5 倍期望周期的帧数）。
    int 统计严重掉帧数();
    // 获取总帧数。
    int64_t 获取总帧数();
    // 获取直方图分档计数（共 16 档），调用者提供长度 16 的数组。
    int 获取直方图(int64_t* 输出数组, int 输出长度);
    // 导出人类可读摘要到调用者缓冲，返回实际写入字节数，失败返回负数。
    int 导出摘要(char* 输出缓冲, int 缓冲长度);
    // 设置期望周期（切换 60Hz/90Hz/120Hz 时调用），参数为纳秒。
    int 设置期望周期(int64_t 周期纳秒);
    // 获取期望周期。
    int64_t 获取期望周期();
    // 判断是否处于低帧率告警状态（连续掉帧超过阈值）。
    bool 是否低帧率告警();
    // 获取连续掉帧计数。
    int 获取连续掉帧计数();
    // 保存快照到文件（二进制环形缓冲转储），失败返回负数并置 errno。
    int 保存快照(const char* 文件路径);
    // 从文件恢复快照。
    int 恢复快照(const char* 文件路径);
    // 分档统计_00：统计帧间隔落在 [0ms, 2ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_00();
    // 分档统计_01：统计帧间隔落在 [2ms, 4ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_01();
    // 分档统计_02：统计帧间隔落在 [4ms, 6ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_02();
    // 分档统计_03：统计帧间隔落在 [6ms, 8ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_03();
    // 分档统计_04：统计帧间隔落在 [8ms, 10ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_04();
    // 分档统计_05：统计帧间隔落在 [10ms, 12ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_05();
    // 分档统计_06：统计帧间隔落在 [12ms, 14ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_06();
    // 分档统计_07：统计帧间隔落在 [14ms, 16ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_07();
    // 分档统计_08：统计帧间隔落在 [16ms, 18ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_08();
    // 分档统计_09：统计帧间隔落在 [18ms, 20ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_09();
    // 分档统计_10：统计帧间隔落在 [20ms, 22ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_10();
    // 分档统计_11：统计帧间隔落在 [22ms, 24ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_11();
    // 分档统计_12：统计帧间隔落在 [24ms, 26ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_12();
    // 分档统计_13：统计帧间隔落在 [26ms, 28ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_13();
    // 分档统计_14：统计帧间隔落在 [28ms, 30ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_14();
    // 分档统计_15：统计帧间隔落在 [30ms, 32ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_15();
    // 分档统计_16：统计帧间隔落在 [32ms, 34ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_16();
    // 分档统计_17：统计帧间隔落在 [34ms, 36ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_17();
    // 分档统计_18：统计帧间隔落在 [36ms, 38ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_18();
    // 分档统计_19：统计帧间隔落在 [38ms, 40ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_19();
    // 分档统计_20：统计帧间隔落在 [40ms, 42ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_20();
    // 分档统计_21：统计帧间隔落在 [42ms, 44ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_21();
    // 分档统计_22：统计帧间隔落在 [44ms, 46ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_22();
    // 分档统计_23：统计帧间隔落在 [46ms, 48ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_23();
    // 分档统计_24：统计帧间隔落在 [48ms, 50ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_24();
    // 分档统计_25：统计帧间隔落在 [50ms, 52ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_25();
    // 分档统计_26：统计帧间隔落在 [52ms, 54ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_26();
    // 分档统计_27：统计帧间隔落在 [54ms, 56ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_27();
    // 分档统计_28：统计帧间隔落在 [56ms, 58ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_28();
    // 分档统计_29：统计帧间隔落在 [58ms, 60ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_29();
    // 分档统计_30：统计帧间隔落在 [60ms, 62ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_30();
    // 分档统计_31：统计帧间隔落在 [62ms, 64ms) 区间的帧数（含边界修正与溢出保护）。
    int 分档统计_31();
    // 垂直同步回调：供 AChoreographer 注册，内部转发至记录帧到达并重挂回调。
    static void 垂直同步回调(long 帧时间纳秒, void* 上下文);

private:
    // 环形缓冲容量（固定 512）。
    static constexpr int 环形容量 = 512;
    // 直方图档数（固定 16）。
    static constexpr int 直方图档数 = 16;
    mutable std::mutex 互斥锁_;
    int 窗口长度_ = 120;
    int64_t 期望周期纳秒_ = 16666666LL;
    int64_t 环形时间_[512] = {};
    int 环形头_ = 0;
    int 环形计数_ = 0;
    int64_t 总帧数_ = 0;
    int64_t 直方图_[16] = {};
    int 连续掉帧_ = 0;
    int64_t 上一帧时间_ = 0;
    bool 已初始化_ = false;
    // 内部工具：计算环形缓冲中有效样本数（受窗口长度与实际计数双重约束）。
    int 有效样本数_内部() const;
    // 内部工具：计算指定下标的帧间隔（纳秒），含首帧保护。
    int64_t 帧间隔_内部(int 环形下标) const;
    // 加固：参数化分档统计入口（边界来自静态查找表，档号 0~31）。
    int 分档统计按档号_内部(int 档号);
    // 内部工具：根据帧间隔更新直方图与连续掉帧计数。
    void 更新直方图与掉帧_内部(int64_t 间隔纳秒);
};
