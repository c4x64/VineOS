package com.hexadecinull.vineos.网络

/** 端口转发管理器：DNAT/SNAT/MASQUERADE，iptables 与 nftables 双后端，真实执行生效。 */
import java.util.concurrent.ConcurrentHashMap
import javax.inject.Inject
import javax.inject.Singleton

/** 转发协议。 */
enum class 转发协议 { TCP, UDP, TCP与UDP }

/** NAT 后端。 */
enum class NAT后端 { 自动, IPTABLES, NFTABLES }

/** 端口映射定义。 */
data class 端口映射(
    val 实例标识: String,
    val 协议: 转发协议,
    val 宿主端口: Int,
    val 容器地址: String,
    val 容器端口: Int,
    val 后端: NAT后端,
    val 已生效: Boolean,
    val 创建时间: Long
)

/** 转发状态汇总。 */
data class 转发汇总(val 总数: Int, val 生效数: Int, val 映射列表: List<端口映射>)

@Singleton
class 端口转发管理器 @Inject constructor(private val 执行器: 特权命令执行器) {
    private val 映射表 = ConcurrentHashMap<String, 端口映射>()
    private fun 键(协议: 转发协议, 宿主端口: Int): String = 协议.name + ":" + 宿主端口

    /** 探测 nft 是否可用。 */
    fun 是否支持Nft(): Boolean = try {
        执行器.探测二进制路径("nft").可用
    } catch (忽略: Exception) {
        false
    }

    /** 探测 iptables 是否可用。 */
    fun 是否支持Iptables(): Boolean = try {
        执行器.探测二进制路径("iptables").可用
    } catch (忽略: Exception) {
        false
    }

    /** 选择后端。 */
    fun 选择后端(期望: NAT后端): NAT后端 = when (期望) {
        NAT后端.自动 -> if (是否支持Nft()) NAT后端.NFTABLES else NAT后端.IPTABLES
        else -> 期望
    }

    /** 构造 iptables DNAT 命令（PREROUTING）。 */
    fun 构造Iptables转发(协议: 转发协议, 宿主端口: Int, 容器地址: String, 容器端口: Int): List<List<String>> {
        命令辅助.校验端口合法(宿主端口)
        命令辅助.校验端口合法(容器端口)
        命令辅助.校验IPv4地址合法(容器地址)
        val 路径 = 执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
        val 协议组 = when (协议) {
            转发协议.TCP -> listOf("tcp")
            转发协议.UDP -> listOf("udp")
            转发协议.TCP与UDP -> listOf("tcp", "udp")
        }
        return 协议组.map { 单协议 ->
            listOf(
                路径, "-t", "nat", "-A", "PREROUTING", "-p", 单协议, "--dport", 宿主端口.toString(), "-j", "DNAT", "--to-destination",
                容器地址 + ":" + 容器端口
            )
        }
    }

    /** 构造 iptables MASQUERADE 命令（POSTROUTING）。 */
    fun 构造伪装(子网: String, 出口网卡: String = "wlan0"): List<String> {
        命令辅助.校验IPv4子网合法(子网)
        val 路径 = 执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
        return listOf(路径, "-t", "nat", "-A", "POSTROUTING", "-s", 子网, "-o", 出口网卡, "-j", "MASQUERADE")
    }

    /** 构造 nft DNAT 语句。 */
    fun 构造Nft转发(协议: 转发协议, 宿主端口: Int, 容器地址: String, 容器端口: Int): String {
        命令辅助.校验端口合法(宿主端口)
        命令辅助.校验端口合法(容器端口)
        val 协议串 = when (协议) {
            转发协议.TCP -> "tcp"
            转发协议.UDP -> "udp"
            转发协议.TCP与UDP -> "tcp"
        }
        return "add rule ip nat prerouting " + 协议串 + " dport " + 宿主端口 + " dnat to " + 容器地址 + ":" + 容器端口
    }

    /** 添加端口映射：真实执行 iptables/nft 双后端。 */
    fun 添加映射(实例标识: String, 协议: 转发协议, 宿主端口: Int, 容器地址: String, 容器端口: Int, 后端: NAT后端 = NAT后端.自动): 端口映射 {
        命令辅助.校验实例名合法(实例标识)
        命令辅助.校验端口合法(宿主端口)
        命令辅助.校验端口合法(容器端口)
        val 实际后端 = 选择后端(后端)
        var 成功 = false
        if (实际后端 == NAT后端.IPTABLES) {
            for (命令 in 构造Iptables转发(协议, 宿主端口, 容器地址, 容器端口)) {
                val 结果 = 执行器.智能执行(命令, true)
                if (结果.是否成功()) {
                    成功 = true
                } else if (结果.错误输出.contains("already") || 结果.错误输出.contains("exists")) {
                    成功 = true
                }
            }
        } else {
            val 路径 = 执行器.探测二进制路径("nft").绝对路径 ?: "nft"
            val 语句 = 构造Nft转发(协议, 宿主端口, 容器地址, 容器端口)
            val 结果 = 执行器.智能执行(listOf(路径, "add", "rule", "ip", "nat", "prerouting") + 语句.split(" ").takeLast(4), true)
            // 兼容性：若 nft 表不存在则回退 iptables
            if (!结果.是否成功()) {
                for (命令 in 构造Iptables转发(协议, 宿主端口, 容器地址, 容器端口)) {
                    if (执行器.智能执行(命令, true).是否成功()) 成功 = true
                }
            } else {
                成功 = true
            }
        }
        // 放行 FORWARD 链
        try {
            val 路径 =
                执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
            执行器.智能执行(listOf(路径, "-A", "FORWARD", "-d", 容器地址, "-p", "tcp", "--dport", 容器端口.toString(), "-j", "ACCEPT"), true)
        } catch (
            忽略: Exception
        ) { }
        val 映射 = 端口映射(实例标识, 协议, 宿主端口, 容器地址, 容器端口, 实际后端, 成功, System.currentTimeMillis())
        映射表[键(协议, 宿主端口)] = 映射
        return 映射
    }

    /** 删除端口映射：真实执行 -D 删除。 */
    fun 删除映射(协议: 转发协议, 宿主端口: Int): Boolean {
        val 映射 = 映射表.remove(键(协议, 宿主端口)) ?: return false
        return try {
            for (命令 in 构造Iptables转发(映射.协议, 映射.宿主端口, 映射.容器地址, 映射.容器端口)) {
                val 删除形 = 命令.toMutableList()
                val 位置 = 删除形.indexOf("-A")
                if (位置 >= 0) 删除形[位置] = "-D"
                执行器.智能执行(删除形, true)
            }
            true
        } catch (忽略: Exception) {
            false
        }
    }

    /** 启用子网伪装：真实执行 MASQUERADE。 */
    fun 启用伪装(子网: String, 出口网卡: String = "wlan0"): 网络命令结果 = 执行器.智能执行(构造伪装(子网, 出口网卡), true)

    /** 查询 NAT 表：真实执行 iptables -t nat -L -n。 */
    fun 查询Nat表(): String {
        val 路径 =
            执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
        val 结果 = 执行器.智能执行(listOf(路径, "-t", "nat", "-L", "-n", "--line-numbers"), false)
        return if (结果.是否成功()) {
            结果.标准输出
        } else {
            "查询失败：" +
                结果.错误输出
        }
    }

    /** 获取汇总。 */
    fun 获取汇总(): 转发汇总 = 转发汇总(映射表.size, 映射表.values.count { it.已生效 }, 映射表.values.sortedBy { it.宿主端口 })

    /** 清理实例全部映射。 */
    fun 清理实例(实例标识: String): Int {
        val 待删 = 映射表.values.filter { it.实例标识 == 实例标识 }
        var 数 = 0
        待删.forEach { if (删除映射(it.协议, it.宿主端口)) 数++ }
        return 数
    }

