package com.hexadecinull.vineos.网络

/** 防火墙规则管理器：iptables/nftables 双后端，链管理、默认策略、 allow/deny/log，真实执行。 */
import java.util.concurrent.ConcurrentHashMap
import javax.inject.Inject
import javax.inject.Singleton

/** 防火墙动作。 */
enum class 防火墙动作 { 放行, 丢弃, 拒绝, 记录 }

/** 防火墙方向。 */
enum class 防火墙方向 { 入站, 出站, 转发 }

/** 防火墙协议。 */
enum class 防火墙协议 { 全部, TCP, UDP, ICMP, ICMPv6 }

/** 防火墙规则。 */
data class 防火墙规则(
    val 编号: String,
    val 方向: 防火墙方向,
    val 协议: 防火墙协议,
    val 来源: String?,
    val 目标: String?,
    val 端口: Int?,
    val 动作: 防火墙动作,
    val 优先级: Int,
    val 备注: String,
    val 已生效: Boolean
)

@Singleton
class 防火墙规则管理器 @Inject constructor(internal val 执行器: 特权命令执行器) {
    private val 规则表 = ConcurrentHashMap<String, 防火墙规则>()

    /** 是否优先 nft。 */
    var 优先Nft: Boolean = true
    private fun 用Nft(): Boolean = 优先Nft && try {
        执行器.探测二进制路径("nft").可用
    } catch (忽略: Exception) {
        false
    }
    private fun 表名(方向: 防火墙方向): String = when (方向) {
        防火墙方向.入站 -> "INPUT"
        防火墙方向.出站 -> "OUTPUT"
        防火墙方向.转发 -> "FORWARD"
    }

    /** 构造 iptables 规则命令。 */
    fun 构造Iptables(方向: 防火墙方向, 协议: 防火墙协议, 来源: String?, 目标: String?, 端口: Int?, 动作: 防火墙动作): List<String> {
        val 路径 = 执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
        val 命令 = mutableListOf(路径, "-A", 表名(方向))
        if (协议 !=
            防火墙协议.全部
        ) {
            命令 +=
                listOf(
                    "-p",
                    when (协议) {
                        防火墙协议.TCP -> "tcp"
                        防火墙协议.UDP -> "udp"
                        防火墙协议.ICMP -> "icmp"
                        防火墙协议.ICMPv6 -> "icmpv6"
                        else -> "all"
                    }
                )
        }
        if (来源 != null) {
            命令辅助.校验IPv4子网合法(if (来源.contains("/")) 来源 else 来源 + "/32")
            命令 += listOf("-s", 来源)
        }
        if (目标 != null) {
            命令 += listOf("-d", 目标)
        }
        if (端口 != null) {
            命令辅助.校验端口合法(端口)
            命令 += listOf("--dport", 端口.toString())
        }
        命令 += listOf(
            "-j",
            when (动作) {
                防火墙动作.放行 -> "ACCEPT"
                防火墙动作.丢弃 -> "DROP"
                防火墙动作.拒绝 -> "REJECT"
                防火墙动作.记录 -> "LOG"
            }
        )
        return 命令
    }

    /** 添加规则：真实执行。 */
    fun 添加规则(方向: 防火墙方向, 协议: 防火墙协议, 来源: String?, 目标: String?, 端口: Int?, 动作: 防火墙动作, 优先级: Int = 100, 备注: String = ""): 防火墙规则 {
        val 编号 = "vine-" + (方向.name.hashCode() and 0xFFFF).toString(36) + "-" + System.currentTimeMillis() % 100000 + "-" + 规则表.size
        var 成功 = false
        if (用Nft()) {
            val 路径 = 执行器.探测二进制路径("nft").绝对路径 ?: "nft"
            val 链 = when (方向) {
                防火墙方向.入站 -> "input"
                防火墙方向.出站 -> "output"
                防火墙方向.转发 -> "forward"
            }
            val 动词 = when (动作) {
                防火墙动作.放行 -> "accept"
                防火墙动作.丢弃 -> "drop"
                防火墙动作.拒绝 -> "reject"
                防火墙动作.记录 -> "log"
            }
            val 结果 = 执行器.智能执行(listOf(路径, "add", "rule", "ip", "filter", 链, 动词), true)
            成功 = 结果.是否成功()
            if (!成功) {
                val 回退 = 执行器.智能执行(构造Iptables(方向, 协议, 来源, 目标, 端口, 动作), true)
                成功 = 回退.是否成功()
            }
        } else {
            val 结果 = 执行器.智能执行(构造Iptables(方向, 协议, 来源, 目标, 端口, 动作), true)
            成功 = 结果.是否成功() || 结果.错误输出.contains("exists")
        }
        val 规则 = 防火墙规则(编号, 方向, 协议, 来源, 目标, 端口, 动作, 优先级, 备注, 成功)
        规则表[编号] = 规则
        return 规则
    }

    /** 删除规则：真实执行 -D。 */
    fun 删除规则(编号: String): Boolean {
        val 规则 = 规则表.remove(编号) ?: return false
        return try {
            val 命令 = 构造Iptables(规则.方向, 规则.协议, 规则.来源, 规则.目标, 规则.端口, 规则.动作).toMutableList()
            val _idx = 命令.indexOf("-A")
            if (_idx >=
                0
            ) {
                命令[_idx] = "-D"
            }
            执行器.智能执行(命令, true).是否成功()
        } catch (忽略: Exception) {
            false
        }
    }

    /** 设置默认策略：iptables -P。 */
    fun 设置默认策略(方向: 防火墙方向, 动作: 防火墙动作): 网络命令结果 {
        val 路径 = 执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
        val 目标 = when (动作) {
            防火墙动作.放行 -> "ACCEPT"
            else -> "DROP"
        }
        return 执行器.智能执行(listOf(路径, "-P", 表名(方向), 目标), true)
    }

    /** 查询 filter 表：真实执行。 */
    fun 查询规则表(): String {
        val 路径 =
            执行器.探测二进制路径("iptables").绝对路径 ?: "iptables"
        val 结果 = 执行器.智能执行(listOf(路径, "-L", "-n", "--line-numbers", "-v"), false)
        return if (结果.是否成功()) {
            结果.标准输出
        } else {
            "查询失败：" +
                结果.错误输出
        }
    }

    /** 列出内存规则。 */
    fun 列出规则(): List<防火墙规则> = 规则表.values.sortedBy { it.优先级 }

    /** 按实例清理。 */
    fun 清理实例规则(实例标识: String): Int {
        val 待删 = 规则表.values.filter { it.备注.contains(实例标识) }
        var 数 = 0
        待删.forEach { if (删除规则(it.编号)) 数++ }
        return 数
    }

