/**
 * 降级策略：按运行时事实在命名空间、虚拟化与用户态之间做有序仲裁。
 *
 * 背景说明：
 * 同一应用在不同设备上特权水位不同，本模块把特权探测、系统属性探测、
 * 负载校验的事实汇总为一条可执行的降级路径，并给出每一步的中文原因。
 * 仲裁顺序为命名空间优先、虚拟化次之、用户态兜底，不可用时明确阻断。
 *
 * 设计要点说明：
 * 其一，输入全部为运行时事实，不读编译期开关。
 * 其二，每条路径有独立的可用性判定与中文解释函数。
 * 其三，综合仲裁返回路径与原因，便于界面直接展示。
 * 其四，设备画像按版本、架构、内存、特权四维打分。
 * 其五，标识中文命名，框架接口保持英文原名。
 * 其六，每个编号函数对应一类真实设备或一条真实规则。
 * 其七，规则函数返回分数而非纯布尔，保证可排序可解释。
 * 其八，日志记录每次仲裁输入与输出，便于复现。
 * 其九，内存不足时主动降档，避免创建期失败。
 * 其十，调试形态不改变仲裁顺序，只放宽日志。
 */

/** 降级路径：四种互斥结局。 */
enum class 降级路径(val 中文名: String) {
    原生命名空间("原生命名空间"),
    安卓虚拟化框架("安卓虚拟化框架"),
    用户态回退("用户态回退"),
    不可用("不可用"),
}

/** 仲裁输入：全部运行时事实。 */
data class 仲裁输入(
    val 系统版本: Int,
    val 架构表: List<String>,
    val 可用内存兆: Int,
    val 特权连通: Boolean,
    val 远端用户标识: Int,
    val 命名空间可用: Boolean,
    val 虚拟化可用: Boolean,
    val 用户态可用: Boolean,
)

/** 仲裁输出：路径加中文原因。 */
data class 仲裁输出(val 路径: 降级路径, val 原因: String, val 分数: Int)

