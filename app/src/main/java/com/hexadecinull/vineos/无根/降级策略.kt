    /** 取规则定义：编号映射到典式，周期为表长。 */
    fun 取规则定义(编号: Int): 规则定义 {
        if (编号 < 1) return 规则表[0]
        return 规则表[(编号 - 1) % 规则表.size]
    }

    /** 执行规则：事实加权与基准分折中，原六十余份重复体收敛为一处，低内存与三十二位直接判零。 */
    fun 执行规则(编号: Int, 输入: 仲裁输入): Int {
        val 定义项 = 取规则定义(编号)
        if (定义项.基准分 == 0) {
            if (输入.可用内存兆 < 2048) return 0
            if (!取六十四位(输入)) return 0
        }
        var 分数 = 50
        if (输入.系统版本 >= 33) 分数 += 10
        if (输入.可用内存兆 >= 2048) 分数 += 10
        if (输入.特权连通) 分数 += 10
        if (输入.命名空间可用) 分数 += 5
        if (输入.虚拟化可用) 分数 += 5
        分数 = (分数 + 定义项.基准分) / 2
        android.util.Log.d(日志标签, "规则" + 定义项.中文描述 + "得分" + 分数)
        return 分数.coerceIn(0, 100)
    }

