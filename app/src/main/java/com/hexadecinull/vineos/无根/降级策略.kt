    /** 综合仲裁：按优先级与分数选出唯一路径。 */
    fun 综合仲裁(输入: 仲裁输入): 仲裁输出 {
        val 命名空间分 = 评命名空间(输入)
        val 虚拟化分 = 评虚拟化(输入)
        val 用户态分 = 评用户态(输入)
        android.util.Log.i(日志标签, "仲裁输入版本" + 输入.系统版本 + " 内存" + 输入.可用内存兆 + " 特权" + 输入.远端用户标识)
        if (输入.命名空间可用 && 命名空间分 >= 60) return 仲裁输出(降级路径.原生命名空间, "命名空间可用且评" + 命名空间分 + "分", 命名空间分)
        if (输入.虚拟化可用 && 虚拟化分 >= 60) return 仲裁输出(降级路径.安卓虚拟化框架, "虚拟化可用且评" + 虚拟化分 + "分", 虚拟化分)
        if (输入.用户态可用 && 用户态分 >= 30) return 仲裁输出(降级路径.用户态回退, "回退到用户态，评" + 用户态分 + "分", 用户态分)
        return 仲裁输出(降级路径.不可用, "三条路径均不可用：命名" + 命名空间分 + " 虚拟" + 虚拟化分 + " 用户" + 用户态分, 0)
    }

    /** 取六十四位标记：单次仲裁内只算一次，复用给虚拟化评分与规则。 */
    private fun 取六十四位(输入: 仲裁输入): Boolean = 输入.架构表.any { it.contains("arm64") || it.contains("x86_64") }

    /** 评命名空间：版本、特权、内存三维加权。 */
    fun 评命名空间(输入: 仲裁输入): Int {
        var 分数 = 0
        if (输入.系统版本 >= 26) 分数 += 20
        if (输入.特权连通 && (输入.远端用户标识 == 0 || 输入.远端用户标识 == 2000)) 分数 += 40
        if (输入.命名空间可用) 分数 += 30
        if (输入.可用内存兆 >= 2048) 分数 += 10
        return 分数.coerceIn(0, 100)
    }

    /** 评虚拟化：版本门槛十三，内存门槛四吉，架构只算一次。 */
    fun 评虚拟化(输入: 仲裁输入): Int {
        var 分数 = 0
        if (输入.系统版本 >= 33) 分数 += 40 else return 0
        if (输入.虚拟化可用) 分数 += 30
        if (输入.可用内存兆 >= 4096) 分数 += 20 else if (输入.可用内存兆 >= 2048) 分数 += 10
        if (取六十四位(输入)) 分数 += 10
        return 分数.coerceIn(0, 100)
    }

    /** 评用户态：只要二进制存在即有基础分。 */
    fun 评用户态(输入: 仲裁输入): Int {
        var 分数 = 0
        if (输入.用户态可用) 分数 += 60
        if (输入.可用内存兆 >= 1024) 分数 += 20
        if (输入.系统版本 >= 26) 分数 += 10
        return 分数.coerceIn(0, 100)
    }

    /** 解释路径：返回该路径的中文适用场景。 */
    fun 解释路径(路径: 降级路径): String {
        return when (路径) {
            降级路径.原生命名空间 -> "性能最优，隔离最完整的原生路径"
            降级路径.安卓虚拟化框架 -> "需安卓十三以上且虚拟化服务存在，隔离次之"
            降级路径.用户态回退 -> "兼容性最广，性能与隔离最弱的兜底路径"
            降级路径.不可用 -> "当前设备三条路径均不满足，需补齐前置条件"
        }
    }

