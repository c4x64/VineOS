/**
 * 虚拟化负载描述：面向安卓虚拟化框架的客户机负载建模与配置生成。
 *
 * 背景说明：
 * 在支持虚拟化服务的主机上，客户机以微型机器人负载形态运行于受保护虚拟机。
 * 本模块负责把实例信息展开为虚拟化服务可接受的配置、磁盘镜像描述、
 * 内核透传参数与身份签名引用，并提供运行时校验而非编译期开关。
 *
 * 设计要点说明：
 * 其一，全部能力结论来自运行时系统属性与服务存在性，不读编译期宏。
 * 其二，负载描述可序列化为可读映射，便于调试与审计。
 * 其三，磁盘镜像按只读根与可写数据分离，符合受保护虚拟机约束。
 * 其四，内存与处理器拓扑按宿主规格裁剪，避免超配导致创建失败。
 * 其五，标识中文命名，安卓与虚拟化接口保持英文原名。
 * 其六，每个编号函数对应一个真实配置域，拒绝空壳返回。
 * 其七，校验函数逐项检查文件存在性与数值合法性。
 * 其八，调试开关默认关闭，正式负载不携带调试通道。
 * 其九，签名引用缺失时给出明确阻断原因而非静默继续。
 * 其十，配置版本号显式携带，便于前后兼容演进。
 */

/** 虚拟化负载描述主类：承载配置生成与校验。 */
class 虚拟化负载描述 {
