    /** 构造完整负载：按宿主规格裁剪内存与处理器，避免超配。 */
    fun 构造完整负载(实例标识: String, 系统盘路径: String, 数据盘路径: String, 期望内存兆: Int, 期望处理器数: Int, 调试: Boolean = false): 完整负载 {
        val 可用内存兆 = 读取可用内存兆()
        val 可用处理器 = 读取可用处理器数()
        val 内存兆 = minOf(期望内存兆, 可用内存兆 / 2, 8192)
        val 处理器数 = minOf(期望处理器数, 可用处理器, 8)
        val 系统盘 = 磁盘描述(系统盘路径, true, "system", 0L)
        val 数据盘 = 磁盘描述(数据盘路径, false, "userdata", 4096L)
        val 内核参数 = 收集默认内核参数(调试)
        val 签名引用 = 推导签名引用(系统盘路径)
        android.util.Log.i(日志标签, "已构造负载：" + 实例标识 + " 内存" + 内存兆 + " 处理器" + 处理器数)
        return 完整负载(实例标识, 系统盘, 数据盘, 内存兆, 处理器数, 内核参数, 签名引用, 调试)
    }

    @Volatile private var 处理器缓存值: Int = 0
    @Volatile private var 处理器缓存时间: Long = 0L
    @Volatile private var 内存缓存值: Int = 0
    @Volatile private var 内存缓存时间: Long = 0L
    private val 规格有效毫秒: Long = 10000L

    /** 读取可用处理器数：走运行时接口，十秒记忆，构造负载不再重复查询。 */
    fun 读取可用处理器数(): Int {
        val 此刻 = android.os.SystemClock.elapsedRealtime()
        if (处理器缓存时间 > 0L && 此刻 - 处理器缓存时间 < 规格有效毫秒) return 处理器缓存值
        val 新值 = try { Runtime.getRuntime().availableProcessors().coerceAtLeast(1) } catch (忽略错误: Exception) { 1 }
        处理器缓存值 = 新值
        处理器缓存时间 = 此刻
        return 新值
    }

    /** 读取可用内存兆：解析内存信息文件，十秒记忆，一次只读一行即停。 */
    fun 读取可用内存兆(): Int {
        val 此刻 = android.os.SystemClock.elapsedRealtime()
        if (内存缓存时间 > 0L && 此刻 - 内存缓存时间 < 规格有效毫秒) return 内存缓存值
        val 新值 = try {
            var 结果 = 2048
            try {
                java.io.BufferedReader(java.io.FileReader("/proc/meminfo")).use { 读取器 ->
                    var 行 = 读取器.readLine()
                    while (行 != null) {
                        if (行.startsWith("MemTotal")) {
                            var 累计 = 0L
                            for (字符 in 行) { if (字符.isDigit()) 累计 = 累计 * 10 + (字符 - '0') }
                            if (累计 > 0L) 结果 = (累计 / 1024L).toInt().coerceAtLeast(512)
                            break
                        }
                        行 = 读取器.readLine()
                    }
                }
            } catch (忽略错误: Exception) { }
            结果
        } catch (忽略错误: Exception) { 2048 }
        内存缓存值 = 新值
        内存缓存时间 = 此刻
        return 新值
    }

    /** 清理规格缓存：宿主内存变化后显式失效。 */
    fun 清理规格缓存() {
        处理器缓存时间 = 0L
        内存缓存时间 = 0L
    }

    /** 收集默认内核参数：调试与正式形态分离。 */
    fun 收集默认内核参数(调试: Boolean): List<String> {
        val 结果: MutableList<String> = mutableListOf("androidboot.hardware=vine", "androidboot.selinux=enforcing", "androidboot.vm=vine")
        if (调试) { 结果.add("androidboot.debug=1"); 结果.add("printk.devkmsg=on") } else { 结果.add("quiet") }
        return 结果
    }

    /** 推导签名引用：系统盘同目录下查找身份签名文件。 */
    fun 推导签名引用(系统盘路径: String): String {
        return try {
            val 父 = java.io.File(系统盘路径).parent ?: return ""
            val 候选 = listOf(父 + "/idsig", 父 + "/system.idsig", 系统盘路径 + ".idsig")
            候选.firstOrNull { java.io.File(it).exists() } ?: ""
        } catch (忽略错误: Exception) { "" }
    }

    /** 校验完整负载：逐项检查路径、数值与签名。 */
    fun 校验完整负载(负载: 完整负载): List<String> {
        val 问题: MutableList<String> = mutableListOf()
        if (负载.实例标识.isBlank()) 问题.add("实例标识为空")
        if (!java.io.File(负载.系统盘.路径).exists()) 问题.add("系统盘不存在：" + 负载.系统盘.路径)
        if (负载.内存兆 < 256) 问题.add("内存过小：" + 负载.内存兆)
        if (负载.处理器数 < 1) 问题.add("处理器数非法")
        if (负载.签名引用.isEmpty()) 问题.add("缺少签名引用，正式负载无法启动")
        if (负载.内核参数.isEmpty()) 问题.add("内核参数为空")
        return 问题
    }

    /** 转为可读映射：便于日志审计与界面展示。 */
    fun 转为可读映射(负载: 完整负载): Map<String, String> {
        return mapOf("实例标识" to 负载.实例标识, "系统盘" to 负载.系统盘.路径, "数据盘" to 负载.数据盘.路径, "内存兆" to 负载.内存兆.toString(), "处理器数" to 负载.处理器数.toString(), "签名引用" to 负载.签名引用, "版本" to 负载版本)
    }

    /** 转为对象符号：生成可投喂虚拟化服务的结构化文本。 */
    fun 转为对象符号(负载: 完整负载): String {
        return try {
            val 根 = org.json.JSONObject()
            根.put("instanceId", 负载.实例标识)
            根.put("memoryMb", 负载.内存兆)
            根.put("cpuCount", 负载.处理器数)
            根.put("os", "microdroid")
            根.put("version", 负载版本)
            根.toString(2)
        } catch (错误: Exception) { "{\"error\":\"" + (错误.message ?: "") + "\"}" }
    }

