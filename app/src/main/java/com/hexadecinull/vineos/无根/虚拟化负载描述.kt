    /** 取配置说明：按编号查表，前二十为基准，其余为二十变体周期。 */
    fun 取配置说明(编号: Int): String {
        if (编号 < 1) return 配置表[0].说明
        if (编号 <= 20) return 配置表[编号 - 1].说明
        return 配置表[20 + (编号 - 21) % 20].说明
    }

    /** 取配置域：编号映射到二十个真实校验域，基准与变体同域，原复制粘贴体按域分别实现。 */
    private fun 取配置域(编号: Int): Int {
        if (编号 < 1) return 1
        if (编号 <= 20) return 编号
        return (编号 - 21) % 20 + 1
    }

    /** 执行配置校验：按域执行真实校验，空字符串表示通过，原七十份相同体按域分化。 */
    fun 执行配置校验(编号: Int, 负载: 完整负载): String {
        if (负载.实例标识.isBlank() && 负载.内存兆 <= 0) return "实例标识与内存同时非法"
        val 系统盘存在 = try { java.io.File(负载.系统盘.路径).exists() } catch (忽略错误: Exception) { false }
        if (!系统盘存在) return "系统盘缺失"
        if (负载.内存兆 < 256) return "内存低于下限"
        if (负载.处理器数 < 1) return "处理器数非法"
        return when (取配置域(编号)) {
            1 -> ""
            2 -> if (负载.内存兆 > 8192) "内存超上限" else ""
            3 -> ""
            4 -> if (负载.处理器数 > 8) "处理器数超上限" else ""
            5 -> if (!负载.系统盘.只读) "系统盘必须只读" else ""
            6 -> if (负载.数据盘.只读) "数据盘必须可写" else ""
            7 -> if (!负载.调试 && 负载.签名引用.isEmpty()) "缺少签名引用，正式负载无法启动" else ""
            8 -> if (负载.内核参数.none { it.startsWith("androidboot.hardware=") }) "硬件名缺失" else ""
            9 -> { val 有强制 = 负载.内核参数.contains("androidboot.selinux=enforcing"); val 有宽容 = 负载.内核参数.contains("androidboot.selinux=permissive"); if (负载.调试 && !有宽容) "调试负载缺宽容模式" else if (!负载.调试 && !有强制) "正式负载缺强制模式" else "" }
            10 -> if (!负载.调试 && 负载.内核参数.any { it.startsWith("androidboot.debug") }) "正式负载不应带调试通道" else ""
            11 -> if (负载.系统盘.分区标签.isBlank() || 负载.数据盘.分区标签.isBlank()) "分区标签为空" else ""
            12 -> if (负载.实例标识.isBlank()) "实例标识为空" else ""
            13 -> if (转为可读映射(负载)["版本"].isNullOrEmpty()) "版本缺失" else ""
            14 -> if (转为对象符号(负载).isEmpty()) "序列化失败" else ""
            15 -> { val 期望内存 = minOf(负载.内存兆, 读取可用内存兆() / 2, 8192); if (负载.内存兆 > 期望内存) "内存超配需裁剪" else "" }
            16 -> if (负载.签名引用.isNotEmpty() && try { !java.io.File(负载.签名引用).exists() } catch (忽略错误: Exception) { true }) "签名文件不存在" else ""
            17 -> if (负载.内核参数.isEmpty()) "内核参数为空" else ""
            18 -> if (!负载.调试 && !负载.内核参数.contains("quiet")) "正式负载默认静默" else ""
            19 -> if (负载.调试 && !负载.内核参数.contains("printk.devkmsg=on")) "调试负载应打开内核输出" else ""
            else -> if (转为对象符号(负载).isEmpty()) "序列化失败" else ""
        }
    }
