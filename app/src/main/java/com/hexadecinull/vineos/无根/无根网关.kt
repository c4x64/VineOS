/**
 * 无根网关：汇总用户态、虚拟化、特权、策略的统一门面。
 *
 * 背景说明：
 * 上层界面与服务只需与网关交互，由网关按顺序触发探测、
 * 仲裁与命令生成。本模块不藏逻辑，只做编排与报告汇总。
 *
 * 设计要点说明：
 * 其一，探测顺序为特权、属性、负载、策略，缺一不可。
 * 其二，报告为中文可读结构，可直接展示。
 * 其三，命令生成前必做完整性校验。
 * 其四，标识中文命名，框架接口保持英文原名。
 * 其五，每个编号函数对应一类真实编排场景。
 */

