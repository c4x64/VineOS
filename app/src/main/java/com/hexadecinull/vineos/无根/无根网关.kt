    /** 生成网关报告：触发全链路探测与仲裁，三秒内同参调用直接复用，避免重复全链路探测。 */
    fun 生成网关报告(根路径: String, 数据目录: String, 强制刷新: Boolean = false): 网关报告 {
        val 键 = 根路径 + "\u0000" + 数据目录
        val 此刻 = android.os.SystemClock.elapsedRealtime()
        if (!强制刷新) {
            val 旧 = 报告缓存
            if (旧 != null && 报告缓存键 == 键 && 此刻 - 报告缓存时间 < 报告有效毫秒) return 旧
        }
        val 特权结论 = 探测器.综合判定()
        val 虚拟化结论 = 属性器.综合判定虚拟化()
        val 二进制 = 内核.定位可执行文件()
        val 输入 = 仲裁输入(android.os.Build.VERSION.SDK_INT, android.os.Build.SUPPORTED_ABIS.toList(), 负载器.读取可用内存兆(), 特权结论.连通, 特权结论.用户标识, 特权结论.连通, 虚拟化结论.通过, 二进制.isNotEmpty())
        val 仲裁 = 策略器.综合仲裁(输入)
        val 描述 = 用户态内核.启动描述(根路径, 数据目录, if (二进制.isEmpty()) "/system/bin/proot" else 二进制)
        val 命令 = try { 内核.构造启动命令(描述) } catch (忽略错误: Exception) { emptyList<String>() }
        android.util.Log.i(日志标签, "网关仲裁：" + 仲裁.路径.中文名 + " " + 仲裁.原因)
        val 报告 = 网关报告(特权结论.连通, 特权结论.用户标识, 特权结论.原因, 虚拟化结论.通过, 虚拟化结论.结论, 仲裁.路径.中文名, 仲裁.原因, 命令.joinToString(" "))
        报告缓存 = 报告
        报告缓存键 = 键
        报告缓存时间 = android.os.SystemClock.elapsedRealtime()
        return 报告
    }

    /** 取修复指引：按报告给出中文操作建议。 */
    fun 取修复指引(报告: 网关报告): List<String> {
        val 建议: MutableList<String> = mutableListOf()
        if (!报告.特权连通) 建议.add("安装并启动特权接口应用后重新探测：" + 报告.特权原因)
        if (!报告.虚拟化通过) 建议.add("虚拟化不可用属正常，请确认用户态回退可用：" + 报告.虚拟化结论)
        if (报告.仲裁路径 == "不可用") 建议.add("三条路径均不可用：检查存储空间与二进制")
        if (报告.命令预览.isEmpty()) 建议.add("命令为空：检查根文件系统是否已解压")
        if (建议.isEmpty()) 建议.add("环境就绪，可直接启动")
        return 建议
    }

