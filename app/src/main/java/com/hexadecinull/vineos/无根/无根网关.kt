    /** 执行编排：按编号查表触发一次网关报告，原五十五份重复体收敛为一处。 */
    fun 执行编排(编号: Int, 根路径: String, 数据目录: String): String {
        if (编号 < 1 || 编号 > 编排表.size) return "编排失败：未知编号" + 编号
        val 定义项 = 编排表[编号 - 1]
        return try {
            val 报告 = 生成网关报告(根路径, 数据目录)
            定义项.前缀 + "：" + 报告.仲裁路径 + "|" + 报告.仲裁原因 + "|特权" + 报告.特权原因
        } catch (错误: Exception) { "编排失败：" + (错误.message ?: "未知错误") }
    }

    /** 取编排说明：按编号查表返回中文说明。 */
    fun 取编排说明(编号: Int): String {
        if (编号 < 1 || 编号 > 编排表.size) return "未知编排"
        return 编排表[编号 - 1].说明
    }
