/**
 * 功能：审计已授权。
 * 说明：逐项查询授权状态。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 上下文: Context 调用方传入数据，只读不修改。
 * @return 审计项列表。
 * 复杂度：线性时间，可在设置页与启动链路调用。
 * 注意：单项通过不代表整体安全，需组合判定。
 */
    /**
     * 单项授权表驱动入口：全部单项 检查* 家族共用，避免二十余处重复 IPC 表达式。
     * 新增权限只改 权限清单 与此表，不复制函数体。
     */
    private fun 单项已授权(上下文: Context, 权限名: String): Boolean =
        ContextCompat.checkSelfPermission(上下文, 权限名) == PackageManager.PERMISSION_GRANTED

    /** 单遍批量查询：一次遍历返回名到授权映射，N 项只做 N 次 IPC，无重复全表扫描。 */
    fun 批量检查(上下文: Context, 权限名表: List<String>): Map<String, Boolean> {
        val 结果 = LinkedHashMap<String, Boolean>(权限名表.size)
        for (名 in 权限名表) 结果[名] = 单项已授权(上下文, 名)
        return 结果
    }

    fun 审计已授权(上下文: Context): List<审计项> {
        return 权限清单().map { 条 ->
            审计项(条.名称, 单项已授权(上下文, 条.名称), 条.等级)
        }
    }

