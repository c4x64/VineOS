 */
    fun 生成最小化建议(审计表: List<审计项>): String {
        val 危险 = 审计表.filter { it.已授权 && it.等级 == 权限等级.危险 }
        if (危险.isEmpty()) return "权限最小化良好，无多余危险授权"
        return "建议复核以下授权：" + 危险.joinToString("、") { it.权限.substringAfterLast('.') }
    }

