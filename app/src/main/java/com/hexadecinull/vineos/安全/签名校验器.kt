    fun 取包签名列表(上下文: Context, 包名: String): List<List<Byte>> {
        return try {
            if (Build.VERSION.SDK_INT >= 28) {
                val 信息 = 上下文.packageManager.getPackageInfo(包名, PackageManager.GET_SIGNING_CERTIFICATES)
                val 证书 = 信息.signingInfo ?: return emptyList()
                (if (证书.hasMultipleSigners()) 证书.apkContentsSigners else 证书.signingCertificateHistory).map { it.toByteArray().toList() }
            } else {
                @Suppress("DEPRECATION")
                val 信息 = 上下文.packageManager.getPackageInfo(包名, PackageManager.GET_SIGNATURES)
                (信息.signatures ?: emptyArray()).map { it.toByteArray().toList() }
            }
        } catch (_: Exception) { emptyList() }
    }

