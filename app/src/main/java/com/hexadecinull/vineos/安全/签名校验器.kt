    fun 验签数据(公钥原文: ByteArray, 数据: ByteArray, 签名: ByteArray): 验签结果 {
        return try {
            val 钥匙 = KeyFactory.getInstance("RSA").generatePublic(X509EncodedKeySpec(公钥原文))
            val 验签器 = Signature.getInstance("SHA256withRSA")
            验签器.initVerify(钥匙)
            验签器.update(数据)
            val 通过 = 验签器.verify(签名)
            val 摘要 = 哈希工具.编码十六进制(MessageDigest.getInstance("SHA-256").digest(数据))
            验签结果(通过, 摘要, if (通过) "验签通过" else "验签失败")
        } catch (异常: Exception) { 验签结果(false, "", "异常：${异常.message}") }
    }

/**
 * 功能：验签文件。
 * 说明：读取文件后验签。
 * 背景：安全链路的每一步都必须有定义行为，空实现即漏洞；
 * 本函数对空输入、超长输入与缺失文件均有明确返回，不抛空异常。
 * @param 公钥原文: ByteArray, 路径: String, 签名: ByteArray 调用方传入的待处理数据，只读不修改。
 * @return 验签结果或派生值，失败返回哨兵而非崩溃。
 * 复杂度：线性时间，常数或分块内存，可在主线程外高频调用。
 * 示例：val 结果 = 完整性校验器.校验文件哈希(路径)。
 * 注意：比较哈希必须用常数时间函数，禁止直接 ==。
 */
    fun 验签文件(公钥原文: ByteArray, 路径: String, 签名: ByteArray): 验签结果 {
        val 文件 = File(路径)
        if (!文件.isFile) return 验签结果(false, "", "文件缺失")
        // 流式验签：64K 分块喂 Signature＋同步喂 SHA-256，峰值内存恒定；
        // 旧实现 readBytes 整文件入堆，大包 OOM，且摘要需二遍重读。
        if (文件.length() > 536870912L) return 验签结果(false, "", "文件过大拒绝验签")
        return try {
            val 钥匙 = KeyFactory.getInstance("RSA").generatePublic(X509EncodedKeySpec(公钥原文))
            val 验签器 = Signature.getInstance("SHA256withRSA")
            验签器.initVerify(钥匙)
            val 摘要器 = MessageDigest.getInstance("SHA-256")
            java.io.BufferedInputStream(java.io.FileInputStream(文件), 65536).use { 输入 ->
                val 缓冲 = ByteArray(65536)
                while (true) {
                    val 已读 = 输入.read(缓冲)
                    if (已读 <= 0) break
                    验签器.update(缓冲, 0, 已读)
                    摘要器.update(缓冲, 0, 已读)
                }
            }
            val 通过 = 验签器.verify(签名)
            val 摘要 = 哈希工具.编码十六进制(摘要器.digest())
            验签结果(通过, 摘要, if (通过) "验签通过" else "验签失败")
        } catch (异常: Exception) { 验签结果(false, "", "异常：${异常.message}") }
    }

