 * 注意：比较哈希必须用常数时间函数，禁止直接 ==。
 */
    fun 解码十六进制(文本: String): ByteArray? {
        if (文本.length % 2 != 0) return null
        val 结果 = ByteArray(文本.length / 2)
        for (i in 结果.indices) {
            val 高 = 文本[i * 2].digitToIntOrNull(16) ?: return null
            val 低 = 文本[i * 2 + 1].digitToIntOrNull(16) ?: return null
            结果[i] = ((高 shl 4) or 低).toByte()
        }
        return 结果
    }

