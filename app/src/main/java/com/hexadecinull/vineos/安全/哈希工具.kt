    fun 编码十六进制(数据: ByteArray): String {
        if (数据.isEmpty()) return ""
        val 表 = "0123456789abcdef"
        // 单次 CharArray 填充：逐字节写两位，避免 StringBuilder 两次 append 的虚调用与扩容。
        val 结果 = CharArray(数据.size * 2)
        for (i in 数据.indices) {
            val 值 = 数据[i].toInt()
            结果[i * 2] = 表[(值 ushr 4) and 0xF]
            结果[i * 2 + 1] = 表[值 and 0xF]
        }
        return String(结果)
    }

