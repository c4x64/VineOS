 * 注意：比较哈希必须用常数时间函数，禁止直接 ==。
 */
    fun 分块哈希(路径: String, 偏移: Long, 长度: Long): String {
        // 流式区间哈希：skip 循环精确定位＋64K 缓冲分块喂摘要，峰值内存恒定；
        // 旧实现 ByteArray(长度) 整区间堆分配，长度可控即 OOM。
        if (偏移 < 0 || 长度 <= 0 || 长度 > 536870912L) return ""
        return try {
            java.io.BufferedInputStream(java.io.FileInputStream(File(路径)), 流式缓冲上限).use { 输入 ->
                var 待跳 = 偏移
                while (待跳 > 0) {
                    val 跳过 = 输入.skip(待跳)
                    if (跳过 <= 0) return@use ""
                    待跳 -= 跳过
                }
                val 摘要 = MessageDigest.getInstance("SHA-256")
                val 缓冲 = ByteArray(流式缓冲上限)
                var 剩余 = 长度
                while (剩余 > 0) {
                    val 取 = if (剩余 > 缓冲.size) 缓冲.size else 剩余.toInt()
                    val 已读 = 输入.read(缓冲, 0, 取)
                    if (已读 <= 0) break
                    摘要.update(缓冲, 0, 已读)
                    剩余 -= 已读
                }
                if (剩余 != 0L) "" else 编码十六进制(摘要.digest())
            }
        } catch (_: Exception) { "" }
    }

