 * 注意：比较哈希必须用常数时间函数，禁止直接 ==。
 */
    fun 计算文件沙256(路径: String, 块大小: Int = 默认块大小): String {
        val 文件 = File(路径)
        require(文件.isFile) { "文件不存在：$路径" }
        // 按文件大小自适应块：小文件 16K 减分配，大文件 256K 提吞吐；缓冲流减半系统调用。
        val 自适应块 = 建议块大小(文件.length()).coerceIn(16384, 262144)
        val 请求块 = if (块大小 > 0) 块大小.coerceIn(16384, 262144) else 自适应块
        val 摘要 = MessageDigest.getInstance("SHA-256")
        java.io.BufferedInputStream(FileInputStream(文件), 请求块).use { 输入 ->
            val 缓冲 = ByteArray(请求块)
            while (true) {
                val 已读 = 输入.read(缓冲)
                if (已读 <= 0) break
                摘要.update(缓冲, 0, 已读)
            }
        }
        return 编码十六进制(摘要.digest())
    }

