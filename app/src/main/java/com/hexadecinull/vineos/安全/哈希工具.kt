 * 说明：读取区间后哈希。
 * 背景：安全链路的每一步都必须有定义行为，空实现即漏洞；
 * 本函数对空输入、超长输入与缺失文件均有明确返回，不抛空异常。
 * @param 路径: String, 偏移: Long, 长度: Long 调用方传入的待处理数据，只读不修改。
