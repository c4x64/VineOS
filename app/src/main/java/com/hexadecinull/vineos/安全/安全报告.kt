/** 安全报告：标题、时间、章节与结论。 */
data class 安全报告(val 标题: String, val 时间: String, val 章节: Map<String, String>, val 结论: String) {
    /** 渲染为可读文本。 */
    fun 渲染(): String {
        val 行 = StringBuilder().append("# ").append(标题).append('\n').append(时间).append("\n\n")
        for ((名, 文) in 章节) 行.append("## ").append(名).append('\n').append(文).append("\n\n")
        return 行.append("结论：").append(结论).append('\n').toString()
    }
}

/** 安全报告构造器。 */
object 安全报告工具 {

/**
 * 功能：当前时间。
 * 说明：格式化当前时间。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 无 调用方传入数据，只读不修改。
 * @return String。
 * 复杂度：线性时间，可在设置页与启动链路调用。
 * 注意：单项通过不代表整体安全，需组合判定。
 */
    fun 当前时间(): String {
        val 格式 = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.CHINA)
        return 格式.format(Date())
    }

/**
 * 功能：脱敏。
 * 说明：掩盖敏感子串。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 文本: String, 敏感: String 调用方传入数据，只读不修改。
 * @return String。
 * 复杂度：线性时间，可在设置页与启动链路调用。
 * 注意：单项通过不代表整体安全，需组合判定。
 */
    fun 脱敏(文本: String, 敏感: String): String {
        if (敏感.isEmpty()) return 文本
        return 文本.replace(敏感, "***")
    }

/**
 * 功能：脱敏多项。
 * 说明：逐项掩盖敏感表。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 文本: String, 敏感表: List<String> 调用方传入数据，只读不修改。
 * @return String。
 * 复杂度：线性时间，可在设置页与启动链路调用。
 * 注意：单项通过不代表整体安全，需组合判定。
 */
    fun 脱敏多项(文本: String, 敏感表: List<String>): String {
        var 结果 = 文本
        for (敏感 in 敏感表) 结果 = 脱敏(结果, 敏感)
        return 结果
    }

/**
 * 功能：组装报告。
 * 说明：汇总审计门禁为报告。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 上下文: Context 调用方传入数据，只读不修改。
 * @return 安全报告。
