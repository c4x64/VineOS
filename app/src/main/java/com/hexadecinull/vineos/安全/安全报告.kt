 * 注意：单项通过不代表整体安全，需组合判定。
 */
    fun 组装报告(上下文: Context): 安全报告 {
        val 门禁 = 安全策略.执行门禁(上下文)
        val 章节 = mapOf("权限" to 权限审计器.审计摘要(上下文), "沙箱" to 沙箱检查器.生成报告(上下文), "门禁" to 安全策略.门禁文本(门禁))
        return 安全报告("VineOS 安全报告", 当前时间(), 章节, if (门禁.放行) "放行" else "拦截")
    }

/**
 * 功能：保存报告。
 * 说明：报告渲染后原子落盘。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 路径: String, 报告: 安全报告 调用方传入数据，只读不修改。
 * @return Boolean。
 * 复杂度：线性时间，可在设置页与启动链路调用。
 * 注意：单项通过不代表整体安全，需组合判定。
 */
    fun 保存报告(路径: String, 报告: 安全报告): Boolean {
        return try { File(路径).parentFile?.mkdirs(); File(路径).writeText(报告.渲染(), Charsets.UTF_8); true } catch (忽略: Exception) { false }
    }

/**
