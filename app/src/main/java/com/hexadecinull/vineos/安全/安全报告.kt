        val 文件 = File(路径)
        return 文件.isFile && (路径.endsWith(".md") || 路径.endsWith(".txt"))
    }

/**
 * 功能：列出报告。
 * 说明：目录下报告文件。
 * 背景：安全审计的每一步都必须有定义行为，含糊即漏报；
 * 本函数对空输入与缺失上下文返回保守结论，不抛空异常。
 * @param 目录: String 调用方传入数据，只读不修改。
 * @return List<String>。
 * 复杂度：线性时间，可在设置页与启动链路调用。
 * 注意：单项通过不代表整体安全，需组合判定。
 */
    fun 列出报告(目录: String): List<String> {
        val 根 = File(目录)
        if (!根.isDirectory) return emptyList()
        return 根.listFiles { f -> f.isFile && (f.name.endsWith(".md") || f.name.endsWith(".txt")) }?.map { it.absolutePath } ?: emptyList()
    }

