     * 注意：耗时操作请放在 Dispatchers.IO，切勿阻塞主线程。
     */
    fun 校验路径可写(路径: String): Boolean {
        val 父 = File(路径).parentFile ?: return false
        if (!父.isDirectory) 父.mkdirs()
        return 父.isDirectory && 父.canWrite()
    }

/**
     * 功能：清理过期审计。
     * 说明：删除过期审计文件。
     * 背景：审计中心串联各模块，任何环节静默失败都会导致误报或漏报；
     * 本函数捕获异常并转为保守结论，不向上传播崩溃。
     * @param 目录: String, 有效毫秒: Long 调用方传入数据，只读不修改。
     * @return Int。
     * 复杂度：线性时间，适合在后台线程执行。
     * 注意：耗时操作请放在 Dispatchers.IO，切勿阻塞主线程。
     */
    fun 清理过期审计(目录: String, 有效毫秒: Long): Int {
        val 根 = File(目录)
        if (!根.isDirectory) return 0
        var 删除 = 0
        for (文件 in 根.listFiles() ?: return 0) {
            if (文件.isFile && System.currentTimeMillis() - 文件.lastModified() > 有效毫秒) {
                if (文件.delete()) 删除++
            }
        }
        return 删除
    }

