/** 审计等级。 */
enum class 审计等级 { 通过, 警告, 拦截 }

/** 审计汇总。 */
data class 审计汇总(val 等级: 审计等级, val 分数: Int, val 权限摘要: String, val 沙箱报告: String, val 门禁摘要: String, val 完整性摘要: String,) {
    /** 可读文本。 */
    fun 渲染(): String = "审计：$等级 分数$分数\n$权限摘要\n$沙箱报告\n$门禁摘要\n$完整性摘要\n"
}

/** 安全审计中心。 */
object 安全审计中心 {

/**
     * 功能：执行一键审计。
     * 说明：串联五大模块并汇总评分。
     * 背景：审计中心串联各模块，任何环节静默失败都会导致误报或漏报；
     * 本函数捕获异常并转为保守结论，不向上传播崩溃。
     * @param 上下文: Context 调用方传入数据，只读不修改。
     * @return 审计汇总。
     * 复杂度：线性时间，适合在后台线程执行。
     * 注意：耗时操作请放在 Dispatchers.IO，切勿阻塞主线程。
     */
    fun 执行一键审计(上下文: Context): 审计汇总 {
        val 权限摘要 = try {
            权限审计器.审计摘要(上下文)
        } catch (忽略: Exception) {
            "权限审计失败"
        }
        val 沙箱报告 = try {
            沙箱检查器.生成报告(上下文)
        } catch (忽略: Exception) {
            "沙箱检查失败"
        }
        val 门禁 = try {
            安全策略.执行门禁(上下文)
        } catch (忽略: Exception) {
            null
        }
        val 门禁摘要 = 门禁?.摘要() ?: "门禁执行失败"
        val 完整性摘要 = try {
            完整性校验器.校验文件存在(上下文.packageCodePath ?: "").说明
        } catch (忽略: Exception) {
            "完整性检查失败"
        }
        val 分数 = try {
            沙箱检查器.综合评分(上下文)
        } catch (忽略: Exception) {
            0
        }
        val 等级 = when {
            门禁 != null && !门禁.放行 -> 审计等级.拦截
            分数 < 60 -> 审计等级.警告
            else -> 审计等级.通过
        }
        return 审计汇总(等级, 分数, 权限摘要, 沙箱报告, 门禁摘要, 完整性摘要)
    }

/**
     * 功能：是否放行启动。
     * 说明：门禁与审计双重放行。
     * 背景：审计中心串联各模块，任何环节静默失败都会导致误报或漏报；
     * 本函数捕获异常并转为保守结论，不向上传播崩溃。
     * @param 上下文: Context 调用方传入数据，只读不修改。
     * @return Boolean。
     * 复杂度：线性时间，适合在后台线程执行。
     * 注意：耗时操作请放在 Dispatchers.IO，切勿阻塞主线程。
     */
    fun 是否放行启动(上下文: Context): Boolean {
        // 复用单次审计结论：执行一键审计内部已求值门禁，旧实现再调执行门禁一次，
        // 重复包管理＋文件 I/O，直接以汇总判定；门禁求值失败保持保守拒绝。
        val 汇总 = try {
            执行一键审计(上下文)
        } catch (忽略: Exception) {
            return false
        }
        if (汇总.等级 == 审计等级.拦截) return false
        if (汇总.门禁摘要 == "门禁执行失败") return false
        return true
    }

/**
     * 功能：保存审计。
     * 说明：汇总渲染后落盘。
     * 背景：审计中心串联各模块，任何环节静默失败都会导致误报或漏报；
     * 本函数捕获异常并转为保守结论，不向上传播崩溃。
     * @param 上下文: Context, 路径: String 调用方传入数据，只读不修改。
     * @return Boolean。
     * 复杂度：线性时间，适合在后台线程执行。
     * 注意：耗时操作请放在 Dispatchers.IO，切勿阻塞主线程。
     */
    fun 保存审计(上下文: Context, 路径: String): Boolean = try {
        val 汇总 = 执行一键审计(上下文)
        File(路径).parentFile?.mkdirs()
        File(路径).writeText(汇总.渲染(), Charsets.UTF_8)
        true
    } catch (忽略: Exception) {
        false
    }

